"One reading of the input: its block systems and their sum, the series data, and the β recurrence."
mutable struct Reading
  names
  L; f; d
  systems::Vector
  c::Vector
  p::Vector
  kreg::Int
end

"c_0..c_n of a reading, extending the series when needed."
function coeffs_upto!(ctx, rd::Reading, n)
  if n >= length(rd.c)
    rd.c = marginal_coeffs(ctx, rd.d, solve_series(ctx, rd.L, rd.f, max(n, 2 * length(rd.c))))
  end
  return rd.c
end

beta_at(ctx, rd::Reading, n) = sum(coeffs_upto!(ctx, rd, n)[1:n+1])

"""
    attempt(ctx, L, f, d; N = 30, pmax = 4, search_readings = true, remainders = true, time_limit = Inf)

Decide S(Δ) = 0 for the normalized marginal system (L, f, d), whose entries are
operators, elements of K or integers. Each diagonal block may be replaced by any of
its `readings`; S does not change (`search_readings = false` keeps the system as
given); blocks whose marginals start at different powers of Y are also compared
after multiplying by the power of Y that aligns them (`aligned`). For every
combination, the cheap stages run first (`cheap_stages`): the a-priori rate, the
annihilator and the zero test, the least annihilator, the rational and polynomial
certificates. Then the channel test runs with periods 1..pmax, across
combinations; for each period, combinations whose β is not a sum of channels are
tried again block by block, with remainders that tend to 0 (`remainder_test`,
unless `remainders = false`). Returns a NamedTuple with `status`

* `:nonzero`: fields n, valuation (ν(β_n) below the a-priori rate), or the exact
  value S(Δ) = `value` ≠ 0 from a rational certificate;
* `:proved`, `method = :zero_marginal`: C = 0 identically (H, R, exceptional);
* `:proved`, `method = :rational`: a rational certificate without pole at T = 0
  for the annihilator A·C = gA used (`annihilator`, R, p, κ = 0; see
  `rational_certificate`);
* `:proved`, `method = :polynomial`: an unshifted certificate of the system (R, P, b0);
* `:proved`, `method = :channels`: period, residue, ratios, coeffs, parts, and the
  bound ν(β_(per·m+r)) ≥ slope·m + κ; with `remainders` (one entry per block:
  `:none`, or the pole order of the fit) the bound is for the channels, and β
  differs from them by remainders that tend to 0;
* `:unknown`: nothing found within the bounds (this is not a disproof); the
  channel search stops early once `time_limit` seconds have passed;

and `reading`, the names of the readings used for the blocks.
"""
function attempt(ctx, L, f, d; time_limit = Inf, kw...)
  DEADLINE[] = time() + time_limit
  try
    return attempt_(ctx, L, f, d; time_limit, kw...)
  finally
    DEADLINE[] = Inf
  end
end

function attempt_(ctx, L, f, d; N = 30, pmax = 4, search_readings = true, remainders = true, time_limit = Inf)
  start = time()
  L, f, d = map(ctx.O, L), map(ctx.O, f), map(ctx.O, d)      # integers, scalars → O
  is_normalized(ctx, L, f, d) || error("input not normalized: need L ≡ I mod t, f and d regular at t = 0")
  sub(b) = (L[b, b], f[b], d[b])
  bs = blocks(L)
  candidates = Reading[]
  plain = [sub(b) for b in bs]
  series = [marginal_coeffs(ctx, B[3], solve_series(ctx, B[1], B[2], 12)) for B in plain]
  for (names, systems) in aligned(ctx, Tuple("Y" for _ in bs), plain, series)
    out = cheap_stages(ctx, names, systems, N)
    out isa Reading || return out
    push!(candidates, out)
  end
  if search_readings                     # the other readings are computed only when needed
    options = [[(name, B, name == "Y" ? series[k] : marginal_coeffs(ctx, B[3], solve_series(ctx, B[1], B[2], 12)))
                for (name, B) in readings(ctx, sub(b)...)] for (k, b) in enumerate(bs)]
    for combo in Iterators.product(options...)
      all(x[1] == "Y" for x in combo) && continue
      for (names, systems) in aligned(ctx, Tuple(x[1] for x in combo), [x[2] for x in combo], [x[3] for x in combo])
        out = cheap_stages(ctx, names, systems, N)
        out isa Reading || return out
        push!(candidates, out)
      end
    end
  end
  cache = Dict{Any, Any}()               # block data for `remainder_test`
  for per in 1:pmax
    for rd in candidates, r in 0:per-1
      time() - start > time_limit && return (; status = :unknown, reason = :time_limit)
      res = progression_test(ctx, rd.p, rd.kreg, n -> beta_at(ctx, rd, n), per, r)
      res === nothing || return (; status = :proved, method = :channels, reading = rd.names, res...)
    end
    remainders || continue
    for rd in candidates, r in 0:per-1
      time() - start > time_limit && return (; status = :unknown, reason = :time_limit)
      res = remainder_test(ctx, rd, per, r, cache)
      res === nothing || return (; status = :proved, method = :channels, reading = rd.names, res...)
    end
  end
  return (; status = :unknown)
end

"""
    aligned(ctx, names, systems, series) -> [(names, systems)]

The combination of block systems itself, and possibly an aligned one. Readings of one
series often differ by a power of Y: the second marginal of an automaton counts its
parts from 0 or from 1 depending on the realization. If the marginals of the blocks
(`series`, their first coefficients) start at different powers of Y and cancel on
these coefficients after multiplying each block by the power Y^s that aligns them,
the aligned combination (d ↦ Y^s d, the same sum S) is returned as well; the zero
test then decides it.
"""
function aligned(ctx, names, systems, series)
  out = [(names, systems)]
  firsts = [findfirst(!iszero, c) for c in series]
  (length(systems) < 2 || any(isnothing, firsts)) && return out
  s = maximum(firsts) .- firsts
  all(iszero, s) && return out
  N = minimum(length, series)
  all(iszero(sum((n > k ? c[n - k] : zero(ctx.K) for (c, k) in zip(series, s)))) for n in 1:N) || return out
  shifted = [(L, f, [ctx.Yo^k * x for x in d]) for ((L, f, d), k) in zip(systems, s)]
  return push!(out, (Tuple(k == 0 ? n : "$n·Y^$k" for (n, k) in zip(names, s)), shifted))
end

"""
    cheap_stages(ctx, names, systems, N) -> result, or a Reading

Steps 1–4 of `attempt` for one combination of readings (block systems, summed by
`block_diag`): the a-priori rate, the
annihilator and the zero test, the least annihilator, the rational and polynomial
certificates. Returns the result of `attempt` if one of them decides, and otherwise
the Reading with its β recurrence for the channel test.
"""
function cheap_stages(ctx, names, systems, N)
  Lc, fc, dc = block_diag(ctx, systems)
  rd = Reading(names, Lc, fc, dc, collect(systems), marginal_coeffs(ctx, dc, solve_series(ctx, Lc, fc, N)), [], 0)
  w = nonzero_witness(ctx, Lc, fc, dc, accumulate(+, rd.c))
  w === nothing || return (; status = :nonzero, n = w[1], valuation = w[2], reading = names)
  H, R = annihilator(ctx, Lc, fc, dc)
  g = ε(ctx, sum(R[j] * fc[j] for j in eachindex(fc)))
  if iszero(g)                                                     # H·C = 0: decide C ≡ 0
    E = exceptional_set(ctx, H)
    cs = coeffs_upto!(ctx, rd, maximum(E; init = 0))
    all(iszero(cs[k + 1]) for k in E) &&
      return (; status = :proved, method = :zero_marginal, reading = names, H, R, exceptional = E)
  end
  cn(n) = n < 0 ? zero(ctx.K) : coeffs_upto!(ctx, rd, n)[n + 1]
  A, gA = reduce_annihilator(ctx, H, g, (Lc, fc, dc), cn)          # A·C = gA, A of least order
  rc = rational_certificate(ctx, A, gA, cn; regular_only = true, max_degree = 120)
  if rc !== nothing && rc.pole <= 0                                # no pole at T = 0: S(Δ) = κ
    iszero(rc.κ) && return (; status = :proved, method = :rational, reading = names, annihilator = A, rc...)
    return (; status = :nonzero, value = rc.κ, reading = names, annihilator = A, rc...)
  end
  cert = polynomial_certificate(ctx, Lc, fc, dc, 3)
  cert === nothing || return (; status = :proved, method = :polynomial, reading = names, cert...)
  p, k0 = beta_recurrence(ctx, A, gA)
  rd.p, rd.kreg = p, first_regular(ctx, p[end], k0)
  return rd
end

