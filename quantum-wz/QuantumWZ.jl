"c Y^b T^a ↦ c Y^a T^b, termwise on normal forms."
swap_op(ctx, h) = operator(ctx, [(c, a, b) for (c, b, a) in pbw_terms(h)])

"""
    transpose_system(ctx, L, f, d) -> (L', f', d')

The marginal system of the same S with the roles of X and Y exchanged. Rebuild
Q_ij = Φ^(-1)(L_ji), e_i = Φ^(-1)(d_i) and an X-free lift r_j of f_j (any lift has the
same S); write Δ = r·w' with Q w' = e (a left realization) and set Y = 1, which
compiles through Ψ(X^a Y^b) = Y^a T^b:

    L'_ij = Ψ(Q_ij) = swap(L_ji),   f'_i = ρ_Y(e_i),   d'_j = Ψ(r_j).
"""
function transpose_system(ctx, L, f, d)
  L, f, d = map(ctx.O, L), map(ctx.O, f), map(ctx.O, d)
  n = length(f)
  Lt = [swap_op(ctx, L[j, i]) for i in 1:n, j in 1:n]
  ft = [operator(ctx, [(c, a, 0) for (c, b, a) in pbw_terms(h)]) for h in d]
  dt = [operator(ctx, [(c, 0, b) for (c, b, a) in pbw_terms(h)]) for h in f]
  return Lt, ft, dt
end

"The system with these blocks on the diagonal (inverse of `blocks`)."
function block_diag(ctx, systems)
  n = sum(length(f) for (_, f, _) in systems)
  L = fill(zero(ctx.O), n, n)
  f, d = elem_type(ctx.O)[], elem_type(ctx.O)[]
  off = 0
  for (Lb, fb, db) in systems
    k = length(fb)
    L[off+1:off+k, off+1:off+k] = Lb
    append!(f, fb); append!(d, db)
    off += k
  end
  return L, f, d
end

"""
    canonical(ctx, L, f, d) -> (H', u, 1) or nothing

A 1×1 system with the same marginal C as the block (L, f, d). From H·C = g
(`annihilator`), remove the left content h(T), the gcd of the left-form coefficients:
H = h(T) H'. Then (H'·C)_n = g_n / h(t^n) where h(t^n) ≠ 0, and it is read from the
data at the finitely many other n, so u = H'·C is an explicit polynomial. If H' ≡ c
mod t for a constant c (after scaling by a power of t), H'/c is normalized and the
unique solution in B̂ of (H'/c)·m = u/c is C itself.
"""
function canonical(ctx, L, f, d; N = 30)
  (; F, O) = ctx
  H, R = annihilator(ctx, L, f, d)
  g = ε(ctx, sum(R[j] * f[j] for j in eachindex(f)))
  lf = left_form(ctx, H)
  cont = reduce(gcd, [numerator(x) for x in values(lf) if !iszero(x)])
  h = F(cont)
  Hp = zdeg(h) > 0 ? from_left_form(ctx, [(b, x // h) for (b, x) in lf]) : H
  bad = zdeg(h) > 0 ? [n for n in 0:poly_profile(ctx, h)[3]-1 if iszero(at_tk(ctx, h, n))] : Int[]
  Du = max(ydeg(g), maximum(bad; init = 0), 0)
  c = marginal_coeffs(ctx, d, solve_series(ctx, L, f, max(N, Du + ydeg(Hp) + 8)))
  u = operator(ctx, [(ycoeff(ctx, Hp, c, n), n, 0) for n in 0:Du])
  @assert all(iszero(ycoeff(ctx, Hp, c, n)) for n in Du+1:Du+5)
  # normalize: H' ≡ c0 mod t after scaling by t^(−v)
  v = minimum(valuation_t(x) for (x, _, _) in pbw_terms(Hp))
  scale(h_) = operator(ctx, [(x * tpow(ctx, -v), b, a) for (x, b, a) in pbw_terms(h_)])
  Hs, us = scale(Hp), scale(u)
  low = [(x, b, a) for (x, b, a) in pbw_terms(Hs) if valuation_t(x) == 0]
  (length(low) == 1 && low[1][2:3] == (0, 0)) || return nothing
  c0 = low[1][1]
  c0 = coeff(numerator(c0), 0) // coeff(denominator(c0), 0)   # the constant c0 mod t
  Hn = operator(ctx, [(x // c0, b, a) for (x, b, a) in pbw_terms(Hs)])
  un = operator(ctx, [(x // c0, b, a) for (x, b, a) in pbw_terms(us)])
  all(valuation_t(x) >= 0 for (x, _, _) in pbw_terms(un)) || return nothing
  return fill(Hn, 1, 1), [un], [one(O)]
end

"""
    readings(ctx, L, f, d) -> [(name, system)]

Systems with the same S as the block (L, f, d) (section "Searching the readings"):
"Y" the block itself, "X" its other marginal (`transpose_system`), and "cY'", "cX'"
the other marginals of the canonical realizations of these (`canonical`).
"""
function readings(ctx, L, f, d)
  out = Any[("Y", (L, f, d)), ("X", transpose_system(ctx, L, f, d))]
  for (name, B) in copy(out)
    cs = canonical(ctx, B...)
    cs === nothing || push!(out, ("c" * name * "'", transpose_system(ctx, cs...)))
  end
  return out
end

