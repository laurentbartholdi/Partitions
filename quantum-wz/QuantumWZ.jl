"""
    euler(ctx)

Euler: odd parts minus distinct parts, Δ = h − h' with

    h − 1 = Y (1 − X − Y²)^(-1) X,      h' − 1 = Y (1 − Y − XY)^(-1) X.

These forms are not normalized, so we use Y m X = t X σ(m) Y with σ(X) = tX, σ(Y) = tY:

    h − 1 = t X P_o^(-1) Y,  P_o = 1 − tX − t²Y²;      h' − 1 = t X P_d^(-1) Y,  P_d = 1 − tY − t²XY.
"""
function euler(ctx)
  (; t, A, X, Y) = ctx
  Po = one(A) - A(t) * X - A(t^2) * Y^2
  Pd = one(A) - A(t) * Y - A(t^2) * X * Y
  return compile(ctx, [Po zero(A); zero(A) Pd], [X, X], [A(t) * Y, -A(t) * Y])
end

"""
    automaton(ctx, n, transitions, start, final) -> (Q, r, e)

Realization of h − 1 = Y (Σ_(w ∈ 𝓛) w) X for the language 𝓛 of an automaton with
states 1..n and transitions (i, j, letter), letter ∈ {ctx.X, ctx.Y}. Moving the
outer Y…X inside as in `euler` gives weight t per letter:
Q = I − Σ t·letter at (i, j),  r = X at `start`,  e = tY at the `final` states.
Use `compile(ctx, automaton(…)...)` or `compile(ctx, difference(…, …)...)`.
"""
function automaton(ctx, n, transitions, start, final)
  (; t, A, X, Y) = ctx
  Q = [i == j ? one(A) : zero(A) for i in 1:n, j in 1:n]
  for (i, j, letter) in transitions
    Q[i, j] -= A(t) * letter
  end
  r = [i == start ? X : zero(A) for i in 1:n]
  e = [i in final ? A(t) * Y : zero(A) for i in 1:n]
  return Q, r, e
end

"""
    automaton(ctx, spec::AbstractString) -> (Q, r, e)

An automaton in the notation "0R1 1R2 1U1 1U∞ 2R1": a transition iVj goes from state
i to state j reading V ∈ {R, U}; 0 is the initial and ∞ the final state. R = Y and
U = X, so the automaton stands for the sum Σ_w w of its accepted words, whose sum S
is the generating function of the words by the number of pairs R…U (Euler's odd
series in the example). Every accepted word must have the form R…U: initial
transitions read R and final ones read U. Then Σ_w w = Y (Σ_w' w') X with w' the
inner paths, realized as in the other method (several initial or final transitions
are allowed).
"""
function automaton(ctx, spec::AbstractString)
  (; t, A, X, Y) = ctx
  edges = [Tuple(match(r"^(\d+|∞)([RU])(\d+|∞)$", e).captures) for e in split(spec)]
  n = maximum(parse(Int, s) for (i, _, j) in edges for s in (i, j) if s != "0" && s != "∞")
  Q = [i == j ? one(A) : zero(A) for i in 1:n, j in 1:n]
  r, e = fill(zero(A), n), fill(zero(A), n)
  for (i, v, j) in edges
    if i == "0"
      (v == "R" && j != "∞") || error("initial transitions must read R: $i$v$j")
      r[parse(Int, j)] += X
    elseif j == "∞"
      v == "U" || error("final transitions must read U: $i$v$j")
      e[parse(Int, i)] += A(t) * Y
    else
      Q[parse(Int, i), parse(Int, j)] -= A(t) * (v == "R" ? Y : X)
    end
  end
  return Q, r, e
end

"The automata of a line \"Automaton[[0R1 …], [0R1 …], …]\", as strings for `automaton`."
function automata(line::AbstractString)
  m = match(r"^\s*Automaton\[(.*)\]\s*$", line)
  m === nothing && error("cannot parse: $line")
  return [String(a.captures[1]) for a in eachmatch(r"\[([^\[\]]*)\]", m.captures[1])]
end

"""
    difference(S1, S2)

Δ1 − Δ2, block diagonal, for two realizations (Q, r, e) or two operator forms
(L, f, d). The zero blocks are integers; `compile` and `attempt` convert them.
"""
function difference((Q1, r1, e1), (Q2, r2, e2))
  n1, n2 = length(r1), length(r2)
  Q = Matrix{Any}(fill(0, n1 + n2, n1 + n2))
  Q[1:n1, 1:n1] = Q1
  Q[n1+1:end, n1+1:end] = Q2
  return Q, [r1; r2], [e1; -e2]
end

"Δ = X − Y: certificate X − Y = (1 − X)(−1) + 1·(1 − Y)."
x_minus_y(ctx) = compile(ctx, fill(one(ctx.A), 1, 1), [one(ctx.A)], [ctx.X - ctx.Y])

"Δ = 1: S(Δ) = 1 ≠ 0."
delta_one(ctx) = compile(ctx, fill(one(ctx.A), 1, 1), [one(ctx.A)], [one(ctx.A)])

"Δ = (1−t)(1−tX)^(-1)(X−1): C = 0, so S(Δ) = 0, but there is no boundary certificate."
function incomplete(ctx)
  (; t, A, X) = ctx
  return compile(ctx, fill(one(A) - A(t) * X, 1, 1), [A(1 - t)], [X - one(A)])
end

