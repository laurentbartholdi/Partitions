"""
    left_form(ctx, h) -> Dict(b => h_b)

Write h ∈ O as Σ_b h_b(T) Y^b with coefficients on the left, h_b ∈ K(T) ⊂ F (z
plays the role of T). Since T^a Y^b = t^(ab) Y^b T^a, a term c Y^b T^a
contributes c t^(−ab) T^a to h_b. In this form

    (h(T) Y^b)·(κ(T) Y^c) = h(T) κ(t^(−b) T) Y^(b+c),

so unknown coefficients h(T) enter linearly; and h·v has coefficients
[Y^n](h·v) = Σ_b h_b(t^n) v_(n−b), a recurrence in n of order deg_Y h.
"""
function left_form(ctx, h)
  out = Dict{Int, elem_type(ctx.F)}()
  for (c, b, a) in pbw_terms(h)
    out[b] = get(out, b, zero(ctx.F)) + toF(ctx, c * tpow(ctx, -a * b)) * ctx.zF^a
  end
  return out
end

"Inverse of `left_form` for coefficients polynomial in T: Σ_b p_b(T) Y^b as an element of O."
function from_left_form(ctx, coefs)
  terms = []
  for (b, x) in coefs, (j, c) in enumerate(zcoeffs(ctx, x))
    iszero(c) || push!(terms, (toK(ctx, c) * tpow(ctx, (j - 1) * b), b, j - 1))
  end
  return operator(ctx, terms)
end

"The diagonal blocks of L: index sets of the connected components of its nonzero pattern."
function blocks(L)
  n = size(L, 1)
  up = collect(1:n)                             # union-find forest
  root(i) = up[i] == i ? i : (up[i] = root(up[i]))
  for i in 1:n, j in 1:n
    iszero(L[i, j]) || (up[root(i)] = root(j))
  end
  comps = Dict{Int, Vector{Int}}()
  for i in 1:n
    push!(get!(comps, root(i), Int[]), i)
  end
  return sort(collect(values(comps)))
end

"""
    annihilator(ctx, L, f, d) -> (H, R)

H ≠ 0 and rows R with

    H·d[i] = Σ_j R_j L[j,i]   (i = 1..n),

so that H·C = Σ_j R_j·f_j =: g is a polynomial in Y. Unknowns are written
H = Σ_(b ≤ v) h_b(T) Y^b and R_j = Σ_(b ≤ v) r_(j,b)(T) Y^b with coefficients in
K(T); the equations are linear over K(T) (`left_form`). For v = 0, 1, 2, … the
kernel of the linear system is computed, so H has least Y-degree under this
common bound; a solution exists for v = n·D (with D the largest Y-degree in L
and d), by counting unknowns against equations as in the elimination lemma.
Denominators are cleared by left multiplication by a polynomial in T, and the
identity is checked in O.

A block-diagonal system is done block by block: with annihilators (H_k, R_k) of
the blocks and a common left multiple H = A_1 H_1 = A_2 H_2 = … (`lclm`), R is
A_k R_k on block k, since H d^(k) = A_k H_k d^(k) = A_k R_k L^(k). This is much
cheaper than one large system.
"""
function annihilator(ctx, L, f, d)
  (; F) = ctx
  n = length(f)
  bs = blocks(L)
  if length(bs) > 1
    parts = [annihilator(ctx, L[b, b], f[b], d[b]) for b in bs]
    As = lclm(ctx, first.(parts))
    H = As[1] * parts[1][1]
    R = fill(zero(ctx.O), n)
    for (b, A, (_, Rb)) in zip(bs, As, parts)
      R[b] = [A * r for r in Rb]
    end
    @assert all(H * d[i] == sum(R[j] * L[j, i] for j in 1:n) for i in 1:n)
    return H, R
  end
  Lc = [left_form(ctx, L[j, i]) for j in 1:n, i in 1:n]
  dc = [left_form(ctx, h) for h in d]
  D = max(1, maximum(maximum(keys(x); init = 0) for x in [vec(Lc); dc]))
  for v in 0:n*D
    unknowns = [(j, b) for j in 0:n for b in 0:v]          # j = 0: H, j ≥ 1: R_j
    eqs = Dict{Tuple{Int, Int}, Int}()                      # (entry i, power Y^e) => row
    entries = []
    for (u, (j, b)) in enumerate(unknowns), i in 1:n
      src, sign = j == 0 ? (dc[i], 1) : (Lc[j, i], -1)
      for (c, κ) in src
        row = get!(eqs, (i, b + c), length(eqs) + 1)
        push!(entries, (row, u, sign * zsub(ctx, κ, -b)))
      end
    end
    M = [zero(F) for _ in 1:length(eqs), _ in 1:length(unknowns)]
    for (row, u, x) in entries
      M[row, u] += x
    end
    for x in kernel_field(F, M)
      all(iszero(x[u]) for (u, (j, _)) in enumerate(unknowns) if j == 0) && continue
      den = reduce(lcm, [denominator(y) for y in x if !iszero(y)])
      x = [y * den for y in x]
      part(j) = from_left_form(ctx, [(b, x[u]) for (u, (jj, b)) in enumerate(unknowns) if jj == j])
      H = part(0)
      R = [part(j) for j in 1:n]
      @assert all(H * d[i] == sum(R[j] * L[j, i] for j in 1:n) for i in 1:n)
      return H, R
    end
  end
  error("no annihilator: L is singular")
end

"""
    lclm(ctx, Hs) -> As

Multipliers A_k with A_1 H_1 = A_2 H_2 = … of least Y-degree (a least common left
multiple of the H_k). In left form A_k = Σ_c a_(k,c)(T) Y^c, and
(a(T) Y^c)(h(T) Y^b) = a(T) h(t^(−c) T) Y^(b+c), so the conditions
A_1 H_1 − A_k H_k = 0 are linear over K(T). The common degree e runs from
max deg H_k to Σ deg H_k, where a solution exists.
"""
function lclm(ctx, Hs)
  (; F) = ctx
  K = length(Hs)
  hs = [left_form(ctx, H) for H in Hs]
  ds = [ydeg(H) for H in Hs]
  for e in maximum(ds):sum(ds)
    unknowns = [(k, c) for k in 1:K for c in 0:e-ds[k]]
    M = [zero(F) for _ in 1:(K-1)*(e+1), _ in eachindex(unknowns)]
    for (u, (k, c)) in enumerate(unknowns), (b, h) in hs[k]
      x = zsub(ctx, h, -c)                     # contribution to Y^(b+c)
      for j in (k == 1 ? (1:K-1) : (k-1:k-1))  # equation block j: A_1 H_1 − A_(j+1) H_(j+1)
        M[(j - 1) * (e + 1) + b + c + 1, u] += k == 1 ? x : -x
      end
    end
    ker = kernel_field(F, M)
    isempty(ker) && continue
    x = ker[1]
    den = reduce(lcm, [denominator(y) for y in x if !iszero(y)])
    x = [y * den for y in x]
    return [from_left_form(ctx, [(c, x[u]) for (u, (kk, c)) in enumerate(unknowns) if kk == k]) for k in 1:K]
  end
  error("no common left multiple")
end

"""
    exceptional_set(ctx, H)

The k ≥ 0 with H_b0(t^k) = 0, where H = Σ_b Y^b H_b(T) and b0 is its lowest
nonzero row. If H·C = 0, coefficient k + b0 of this identity reads
H_b0(t^k) c_k = −(terms in c_0, …, c_(k−1)); so C = 0 iff c_k = 0 for every
exceptional k. The set is finite and is found by `poly_profile`.
"""
function exceptional_set(ctx, H)
  b0 = minimum(b for (_, b, _) in pbw_terms(H))
  Hb0 = sum(toF(ctx, c) * ctx.zF^a for (c, b, a) in pbw_terms(H) if b == b0)
  _, _, J = poly_profile(ctx, Hb0)
  return [k for k in 0:J-1 if iszero(at_tk(ctx, Hb0, k))]
end

"""
    reduce_annihilator(ctx, H, g, sys, c) -> (A, gA)

H·C = g comes from the system and is minimal for it, not for C: C can satisfy an
equation of lower order, for instance when the two sides of a difference share a
component, or when C is a polynomial. This returns a right factor A of H of least
order with A·C = gA a polynomial, or (H, g) when none is found.

A = Σ_(b ≤ r) a_b(T) Y^b (left form) with a_b of degree ≤ δ solves
Σ_b a_b(t^n) c_(n−b) = 0 for n = n0, …: a linear system over K = Q(t) whose entries
c_n have large t-degree. The least r, then the least δ, are found on modular images
(t ↦ T0 in GF(PRIME), `marginal_mod`) with twice as many equations as unknowns; the
one-dimensional kernel is then reconstructed from its images at further points
(`reconstruct_kernel`), or, for small systems, computed over K. The guess is proved by
`check_factor`. The search is limited to `max_unknowns` coefficients (and the exact
fallback to `budget`); only completeness depends on these bounds.
"""
function reduce_annihilator(ctx, H, g, sys, c; extra = 4, max_unknowns = 32, budget = 5_000)
  (; K, t, zF) = ctx
  B = ydeg(H)
  B <= 0 && return H, g
  δmax = min(16, maximum(zdeg, values(left_form(ctx, H))) + 4)
  n0 = max(ydeg(g), 0) + B + 1
  cols(r, δ) = [(b, k) for b in 0:r for k in 0:δ]
  guess(R, cv, tt, r, δ, m) = [n >= b ? tt^(n * k) * cv(n - b) : zero(R) for n in n0:n0+m-1, (b, k) in cols(r, δ)]
  Fp = GF(PRIME)
  cm = try
    marginal_mod(ctx, sys..., n0 + 2 * max_unknowns + extra, Fp)
  catch
    return H, g
  end
  nullity(r, δ, m) = length(cols(r, δ)) - rank(matrix(Fp, guess(Fp, n -> cm[n + 1], Fp(T0), r, δ, m)))
  for r in 0:B-1
    U(δ) = (r + 1) * (δ + 1)
    δr = min(δmax, max_unknowns ÷ (r + 1) - 1)                # U(δ) ≤ max_unknowns
    δr < 0 && break
    nullity(r, δr, 2U(δr) + extra) > 0 || continue
    δ = findfirst(δ -> nullity(r, δ, 2U(δ) + extra) > 0, 0:δr) - 1
    m = nullity(r, δ, U(δ) + 2) == 1 ? U(δ) + 2 : 2U(δ) + extra
    _, piv0 = rref_field(Fp, guess(Fp, n -> cm[n + 1], Fp(T0), r, δ, m))
    length(piv0) == U(δ) - 1 || continue
    free = only(setdiff(1:U(δ), piv0))
    function kernel_at(τ)                                     # normalized: entry `free` = 1
      cτ = marginal_mod(ctx, sys..., n0 + m, Fp, τ)
      E, piv = rref_field(Fp, guess(Fp, n -> cτ[n + 1], τ, r, δ, m))
      piv == piv0 || return nothing
      v = [k == free ? one(Fp) : zero(Fp) for k in 1:U(δ)]
      for (i, k) in enumerate(piv)
        v[k] = -E[i, free]
      end
      return v
    end
    x = reconstruct_kernel(ctx, Fp, kernel_at, U(δ))
    if x === nothing                                          # exact kernel, if small
      y = c(n0 + m - 1)
      U(δ) * (degree(numerator(y)) + degree(denominator(y))) > budget && return H, g
      ker = kernel_field(K, guess(K, c, t, r, δ, m))
      isempty(ker) && continue
      x = ker[1]
    end
    a = Dict(b => sum(toF(ctx, v) * zF^k for ((bb, k), v) in zip(cols(r, δ), x) if bb == b) for b in 0:r)
    res = check_factor(ctx, H, g, a, c, n0)
    res === nothing || return res
  end
  return H, g
end

"""
    check_factor(ctx, H, g, a, c, n0) -> (A, gA) or nothing

Proof that A = Σ_b a_b(T) Y^b satisfies A·C = gA, with gA the part of A·C below
degree n0. Right division in left form, using (q(T) Y^j)(a(T) Y^c) = q(T) a(t^(−j) T) Y^(j+c),
gives H = Q·A; with D(T) a common denominator, Q̃ = D(T)·Q has polynomial
coefficients and Q̃·A = D(T)·H (checked in O). If Q̃·gA = D(T)·g, then u = A·C − gA
satisfies Q̃·u = D(T)·(H·C − g) = 0, and u = 0 as soon as u_k = 0 for k up to the
largest exceptional index of Q̃ (`exceptional_set`).
"""
function check_factor(ctx, H, g, a, c, n0)
  (; F, K) = ctx
  filter!(p -> !iszero(p[2]), a)
  r = maximum(keys(a))
  rem = left_form(ctx, H)
  B = maximum(keys(rem))
  Q = Dict{Int, elem_type(F)}()
  for j in B-r:-1:0
    x = get(rem, j + r, zero(F))
    iszero(x) && continue
    Q[j] = x // zsub(ctx, a[r], -j)
    for (b, ab) in a
      rem[j + b] = get(rem, j + b, zero(F)) - Q[j] * zsub(ctx, ab, -j)
    end
  end
  all(iszero, values(rem)) || return nothing
  D = F(reduce(lcm, [denominator(q) for q in values(Q)]))
  Qt = from_left_form(ctx, [(j, D * q) for (j, q) in Q])
  A = from_left_form(ctx, collect(a))
  Dop = from_left_form(ctx, [(0, D)])
  Qt * A == Dop * H || return nothing
  Ac(n) = sum((toK(ctx, at_tk(ctx, ab, n)) * c(n - b) for (b, ab) in a if n >= b); init = zero(K))
  gA = [Ac(n) for n in 0:n0-1]
  gn(p, n) = sum((x for (x, b, _) in pbw_terms(p) if b == n); init = zero(K))
  qs = left_form(ctx, Qt)
  for n in 0:max(n0 - 1 + maximum(keys(qs)), ydeg(g))               # Q̃·gA = D(T)·g
    lhs = sum((toK(ctx, at_tk(ctx, q, n)) * gA[n - j + 1] for (j, q) in qs if 0 <= n - j < n0); init = zero(K))
    lhs == toK(ctx, at_tk(ctx, D, n)) * gn(g, n) || return nothing
  end
  E = exceptional_set(ctx, Qt)
  all(iszero(Ac(n)) for n in n0:maximum(E; init = -1)) || return nothing
  return A, operator(ctx, [(x, n - 1, 0) for (n, x) in enumerate(gA) if !iszero(x)])
end

