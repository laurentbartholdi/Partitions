# 4. Boundary certificates   (sections "Rational operator certificates", "Poles at T = 0")
# =============================================================================

"Λ(h) ∈ F: evaluation at Y = 1 in normal order, Y^b T^a ↦ z^a. Its kernel is (1−Y)·O."
Λ(ctx, h) = sum((toF(ctx, c) * ctx.zF^a for (c, _, a) in pbw_terms(h)); init = zero(ctx.F))

"ε(h) = h · 1, the polynomial obtained by dropping T: Y^b T^a ↦ Y^b."
ε(ctx, h) = operator(ctx, [(c, b, 0) for (c, b, _) in pbw_terms(h)])

"""
    divide_by_1mY(ctx, h)

The operator P with (1 − Y)·P = h. Left multiplication by Y does not involve the
relation, so for each power T^a this is the division of Σ_b h_(b,a) Y^b by 1 − Y:
the coefficients of P are the cumulative sums p_(b,a) = Σ_(b' ≤ b) h_(b',a).
Raises an error unless Λ(h) = 0.
"""
function divide_by_1mY(ctx, h)
  hc = Dict((b, a) => c for (c, b, a) in pbw_terms(h))
  Pterms = []
  for a in unique(a for (_, a) in keys(hc))
    acc = zero(ctx.K)
    for b in 0:maximum(b for (b, a2) in keys(hc) if a2 == a)
      acc += get(hc, (b, a), zero(ctx.K))
      push!(Pterms, (acc, b, a))
    end
    iszero(acc) || error("not divisible by 1 - Y")
  end
  return operator(ctx, Pterms)
end

"""
    polynomial_certificate(ctx, L, f, d, D)

Search rows R ∈ K[T]^n of T-degree ≤ D such that

    Λ(Σ_j R_j L[j,i]) = Λ(d[i])   for i = 1..n,     Σ_j (R_j · f_j)(1) = 0.

The unknown coefficient r_(j,c) of T^c in R_j multiplies Λ(T^c L[j,i]) in
equation i and Λ(T^c f_j)(1) = f_j(t^c) in the last one. From a solution,

    P_i = (d[i] − Σ_j R_j L[j,i]) / (1 − Y),    b0 = ε(Σ_j R_j f_j) / (1 − Y),

so that d = (1−Y)P + R L (checked in O), and b = Σ_i P_i·m_i + b0 converges.
Returns (; R, P, b0), or `nothing`.
"""
function polynomial_certificate(ctx, L, f, d, D)
  (; F, O, Yo, T) = ctx
  n = length(f)
  unknowns = [(j, c) for j in 1:n for c in 0:D]
  lhs = [[zcoeffs(ctx, Λ(ctx, T^c * L[j, i])) for i in 1:n] for (j, c) in unknowns]
  target = [zcoeffs(ctx, Λ(ctx, d[i])) for i in 1:n]
  E = max(0, maximum(length(p) for p in [target; reduce(vcat, lhs)]) - 1)
  at(cs, e) = e < length(cs) ? cs[e + 1] : zero(F)
  row(i, e) = (i - 1) * (E + 1) + e + 1
  last_row = n * (E + 1) + 1
  M = [zero(F) for _ in 1:last_row, _ in eachindex(unknowns)]
  rhs = [zero(F) for _ in 1:last_row]
  for (u, (j, c)) in enumerate(unknowns)
    for i in 1:n, e in 0:E
      M[row(i, e), u] = at(lhs[u][i], e)
    end
    M[last_row, u] = at_tk(ctx, Λ(ctx, T^c * f[j]), 0)
  end
  for i in 1:n, e in 0:E
    rhs[row(i, e)] = at(target[i], e)
  end
  x = solve_field(ctx.K, over_K(ctx, M), over_K(ctx, rhs))
  x === nothing && return nothing
  R = [sum(O(x[u]) * T^c for (u, (jj, c)) in enumerate(unknowns) if jj == j) for j in 1:n]
  RL = [sum(R[j] * L[j, i] for j in 1:n) for i in 1:n]
  P = [divide_by_1mY(ctx, d[i] - RL[i]) for i in 1:n]
  b0 = divide_by_1mY(ctx, ε(ctx, sum(R[j] * f[j] for j in 1:n)))
  @assert all(d[i] == (one(O) - Yo) * P[i] + RL[i] for i in 1:n)
  return (; R, P, b0)
end

"""
    universal_denominator(ctx, a) -> U

Abramov's bound for Σ_(b=0..B) a_b(z) y(t^b z) = rhs, a_0, a_B ≠ 0: every rational
solution is N/(z^k U) with N a polynomial. A factor u of a denominator starts a
chain u(z), u(tz), …, u(t^s z) whose first element divides a_0(z) and whose last
divides A(z) = a_B(t^(−B) z). So, for s from the largest dispersion down to 0,
d = gcd(A(z), a_0(t^s z)) contributes d(z) d(t^(−1) z) ⋯ d(t^(−s) z). Factors z
are left out (the pole at z = 0 is bounded separately).
"""
function universal_denominator(ctx, a)
  (; F, R2, zq) = ctx
  strip_z(p) = divexact(p, zq^minimum(e[2] for e in AbstractAlgebra.exponent_vectors(p)))
  A = strip_z(numerator(zsub(ctx, a[end], 1 - length(a))))
  B = strip_z(numerator(a[1]))
  shifts = Int[]
  for (u, _) in factor_over_K(ctx, F(B)), (v, _) in factor_over_K(ctx, F(A))
    s = shift_of(ctx, u, v)                      # v = u(t^s z)
    s === nothing || s < 0 || push!(shifts, s)
  end
  U = one(F)
  for s in sort(unique(shifts); rev = true)
    d = gcd(A, numerator(zsub(ctx, F(B), s)))
    degree(d, 2) > 0 || continue
    A = divexact(A, d)
    B = divexact(B, gcd(B, numerator(zsub(ctx, F(d), -s))))
    U *= prod(zsub(ctx, F(d), -j) for j in 0:s)
  end
  return U
end

"""
    polynomial_solution(ctx, coef, rhs, dmax, nzero) -> coefficients of N, or nothing

A polynomial N = Σ_(i ≤ dmax) n_i z^i with n_0 = ⋯ = n_(nzero−1) = 0 and
Σ_b coef_b(z) N(t^b z) = rhs(z), by forward substitution. With v the least order of
the coef_b, the coefficient of z^(v+i) reads χ(t^i) n_i = (terms in n_0..n_(i−1)),
χ(W) = Σ_b [z^v] coef_b W^b. Where χ(t^i) = 0, n_i is a free parameter and the
equation is a condition; the remaining coefficients are conditions too. So the n_i
are affine in the free parameters, which solve a small linear system over K.
"""
function polynomial_solution(ctx, coef, rhs, dmax, nzero)
  (; K, t) = ctx
  cb = [[toK(ctx, x) for x in zcoeffs(ctx, c)] for c in coef]       # cb[b+1][k+1] = [z^k] coef_b
  rk = [toK(ctx, x) for x in zcoeffs(ctx, rhs)]
  at(c, k) = 0 <= k < length(c) ? c[k + 1] : zero(K)
  B, top = length(cb) - 1, maximum(length, cb) - 1
  v = minimum(findfirst(!iszero, c) - 1 for c in cb if any(!iszero, c))
  tp = [t^(b * j) for b in 0:B, j in 0:dmax]
  χ(i) = sum(at(cb[b + 1], v) * tp[b + 1, i + 1] for b in 0:B)
  free = [i for i in 0:dmax if iszero(χ(i))]
  m = length(free)
  unit(k) = [j == k ? one(K) : zero(K) for j in 0:m]               # k = 0: the constant part
  n, conds = Vector{elem_type(K)}[], Vector{elem_type(K)}[]
  for e in 0:top+dmax
    s = [at(rk, e) * x for x in unit(0)]
    for j in max(0, e - top):min(e - v - 1, dmax), b in 0:B
      x = at(cb[b + 1], e - j)
      iszero(x) || (s = [s[k] - x * tp[b + 1, j + 1] * n[j + 1][k] for k in 1:m+1])
    end
    i = e - v
    if 0 <= i <= dmax && !(i in free)
      push!(n, [x * inv(χ(i)) for x in s])
    else
      0 <= i <= dmax && push!(n, unit(findfirst(==(i), free)))
      push!(conds, s)                                              # s = 0
    end
  end
  append!(conds, n[1:min(nzero, dmax + 1)])                       # n_0 = ⋯ = n_(nzero−1) = 0
  λ = elem_type(K)[]
  if m == 0
    all(c -> iszero(c[1]), conds) || return nothing
  else
    λ = solve_field(K, [c[k + 1] for c in conds, k in 1:m], [-c[1] for c in conds])
    λ === nothing && return nothing
  end
  return [x[1] + sum((x[k + 1] * λ[k] for k in 1:m); init = zero(K)) for x in n]
end

"""
    rational_certificate(ctx, H, g, c) -> (; R, p, pole, κ) or nothing

A certificate 1 = (1 − Y)P + R(T)·H with R ∈ K(T) (section "Rational certificates").
Applied to C, with H·C = g, it gives c_n = q_n − q_(n−1) + R(t^n) g_n, where
q_n = [Y^n](P·C) = Σ_j p_j(t^(n−j)) c_(n−j) for P = Σ_j Y^j p_j(T). Hence
β_n = q_n + κ for all large n, with a constant κ. If the p_j have no pole at
T = 0 (`pole` ≤ 0), then q_n → 0 and S(Δ) = κ exactly; a pole of order s at T = 0
is a shift by s, and then the certificate identifies b but does not prove that it
converges.

R solves Λ(R·H) = Σ_b a_b(z) R(t^b z) = 1 with a_b(z) = h_b(t^b z), where
H = Σ_b h_b(T) Y^b in left form: a scalar linear q-difference equation. Its rational
solutions are N/(z^k U) (`universal_denominator`). The pole order k at z = 0 is
bounded by the indicial equation at 0: if R ~ r z^(−k), the lowest term of the
left side is r z^(v−k) χ_0(t^(−k)), χ_0(W) = Σ_b [z^v] a_b W^b, so k = v or
χ_0(t^(−k)) = 0. The degree of N is bounded in the same way at z = ∞. The
coefficients of N follow by forward substitution (`polynomial_solution`), first
with the least pole order at 0 (only without pole if `regular_only`). If the
cleared denominator has degree above `max_degree`, nothing is searched (a search
bound). c(n) returns c_n.
"""
function rational_certificate(ctx, H, g, c; regular_only = false, max_degree = Inf)
  (; F, K, tF, zF) = ctx
  hs = left_form(ctx, H)
  B = maximum(keys(hs))
  a = [zsub(ctx, get(hs, b, zero(F)), b) for b in 0:B]       # a[b+1] = h_b(t^b z)
  b0 = findfirst(!iszero, a) - 1                             # R(t^b z) for b ≥ b0 only:
  ã = a[b0+1:end]                                            # solve for R̃(z) = R(t^b0 z)
  Bt = length(ã) - 1
  if Bt == 0                                                 # ã_0(z) R̃(z) = 1
    Rs = [inv(ã[1])]
  else
    U = universal_denominator(ctx, ã)
    lows = [iszero(x) ? nothing : extremes(ctx, x) for x in ã]   # (low exp, its coeff, deg, lead)
    v = minimum(l[1] for l in lows if l !== nothing)
    χ0 = [l !== nothing && l[1] == v ? l[2] : zero(F) for l in lows]
    ks = [-tval(W) for W in roots_in_K(ctx, χ0) if tval(W) < 0 && W == inv(tF)^(-tval(W))]
    k = max(0, v, maximum(ks; init = 0))
    Ut = [zsub(ctx, U, b) for b in 0:Bt]
    W = F(reduce(lcm, [numerator(x) for x in Ut]))          # common denominator of the U(t^b z)
    zdeg(W) > max_degree && return nothing                   # a search bound
    coef = [ã[b + 1] * inv(tF)^(b * k) * W // Ut[b + 1] for b in 0:Bt]
    rhs = zF^k * W
    D = maximum(zdeg, coef)
    χ∞ = [zdeg(x) == D ? zcoeffs(ctx, x)[end] : zero(F) for x in coef]
    ds = [tval(W) for W in roots_in_K(ctx, χ∞) if tval(W) >= 0 && W == tF^tval(W)]
    dmax = max(zdeg(rhs) - D, maximum(ds; init = -1))
    dmax < 0 && return nothing
    w = v                                                    # least z-order of the ã_b
    # least pole order s of R·H at 0: N must vanish to order k − w − s at z = 0
    Rs = elem_type(F)[]
    for s in 0:(regular_only ? 0 : max(0, k - w))
      x = polynomial_solution(ctx, coef, rhs, dmax, k - w - s)
      x === nothing && continue
      push!(Rs, from_zcoeffs(ctx, [toF(ctx, y) for y in x]) // (zF^k * U))
      break
    end
    isempty(Rs) && return nothing
  end
  R = zsub(ctx, Rs[1], -b0)                                  # R(z) = R̃(t^(−b0) z)
  e = [zsub(ctx, R, b) * a[b + 1] for b in 0:B]              # (R h_b)(t^b z)
  p = accumulate(+, [(b == 0 ? one(F) : zero(F)) - e[b + 1] for b in 0:B])
  @assert iszero(p[end])                                     # Λ(1 − R·H) = 0
  p = p[1:end-1]
  zord(x) = extremes(ctx, F(numerator(x)))[1] - extremes(ctx, F(denominator(x)))[1]
  pole = maximum((-zord(x) for x in p if !iszero(x)); init = 0)   # pole order at T = 0
  # c_n = q_n − q_(n−1) holds once n > deg g and n is past the zeros and poles of R
  # and of the p_j at the points t^m (`val_profile`); then β_n − q_n is constant
  J = maximum((val_profile(ctx, x)[3] for x in [p; R] if !iszero(x)); init = 0)
  N0 = max(ydeg(g) + 1, J + B)
  q(n) = sum((toK(ctx, at_tk(ctx, p[j + 1], n - j)) * c(n - j) for j in 0:B-1 if n - j >= 0); init = zero(ctx.K))
  β(n) = sum(c(i) for i in 0:n)
  κ = β(N0) - q(N0)
  all(β(n) - q(n) == κ for n in N0+1:N0+B+1) || return nothing    # sanity check
  return (; R, p, pole, κ)
end

