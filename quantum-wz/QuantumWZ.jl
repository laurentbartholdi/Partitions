"""
    beta_recurrence(ctx, H, g) -> (p, k0)

From H·C = g and C = (1 − Y) b: H(1 − Y)·b = g. Writing H(1 − Y) = Σ_b Y^b H'_b(T)
with rows b0..b1, the coefficient of Y^(k+b1) gives, for k ≥ k0 = deg g − b1 + 1,

    Σ_(i=0..ρ) p_i(t^k) β_(k+i) = 0,     p_i(z) = H'_(b1−i)(t^i z),   ρ = b1 − b0,

with p_i ∈ F polynomials in z.
"""
function beta_recurrence(ctx, H, g)
  (; tF, zF, F) = ctx
  Hp = H * (one(ctx.O) - ctx.Yo)
  rows = Dict{Int, Vector{Any}}()
  for (c, b, a) in pbw_terms(Hp)
    push!(get!(rows, b, []), (c, a))
  end
  b0, b1 = extrema(keys(rows))
  p = [sum((toF(ctx, c) * tF^(i * a) * zF^a for (c, a) in get(rows, b1 - i, [])); init = zero(F)) for i in 0:b1-b0]
  return p, max(0, ydeg(g) - b1 + 1)
end

"""
    section_recurrence(ctx, p, per, r) -> q

A recurrence  Σ_(i=0..k) q_i(t^m) x_(m+i) = 0  for x_m = β_(per·m + r), valid when
per·m + r is past the singularities of p. The recurrence of β in companion form is
v_(k+1) = A(t^k) v_k with v_k = (β_k, …, β_(k+ρ−1)). Then
v_(per·m+r+per) = B(t^m) v_(per·m+r) with B(ζ) = A^[per](t^r ζ^per), and the
Krylov rows w_0 = e_1, w_(j+1)(ζ) = w_j(tζ) B(ζ) give x_(m+j) = w_j(t^m)·v_(per·m+r).
The first w_k in the F-span of w_0..w_(k−1) gives the recurrence (denominators
cleared, common factor removed); `nothing` once `DEADLINE` has passed.
"""
function section_recurrence(ctx, p, per, r)
  (; F) = ctx
  ρ = length(p) - 1
  A = [j == i + 1 ? one(F) : zero(F) for i in 1:ρ, j in 1:ρ]      # companion matrix
  for i in 1:ρ
    A[ρ, i] = -p[i] // p[ρ + 1]
  end
  Ap = A
  for j in 1:per-1
    time() > DEADLINE[] && return nothing
    Ap = matmul(map(h -> zsub(ctx, h, j), A), Ap)
  end
  B = map(h -> zsub(ctx, h, r, per), Ap)
  W = [[i == 1 ? one(F) : zero(F) for i in 1:ρ]]                  # Krylov rows w_0, w_1, …
  while true
    time() > DEADLINE[] && return nothing
    nxt = vec(matmul(permutedims(map(h -> zsub(ctx, h, 1), W[end])), B))
    c = solve_field(F, [w[i] for i in 1:ρ, w in W], nxt)          # nxt = Σ_j c_j w_j ?
    if c !== nothing
      q = [[-x for x in c]; one(F)]
      den = reduce(lcm, [denominator(x) for x in q if !iszero(x)])
      num = [numerator(x * den) for x in q]
      g = reduce(gcd, [x for x in num if !iszero(x)])
      return [F(divexact(x, g)) for x in num]
    end
    push!(W, nxt)
  end
end

