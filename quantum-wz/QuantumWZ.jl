"""
    QuantumWZ

Sums of quantum-rational functions, following the paper "Quantum-rational sums
and holonomic boundary certificates" (section names below refer to it).

# Algebras and fields
Oscar PBW algebras over K = Q(t):

    A = K<X,Y> / (YX - tXY)     quantum plane,      normal monomials X^a Y^b
    O = K<Y,T> / (TY - tYT)     operator algebra,   normal monomials Y^b T^a

O acts on power series in Y by  (Y^b T^a) · v(Y) = Y^b v(t^a Y).
Recurrences use F = Q(t, z), the fraction field of the Flint polynomial ring
Q[t, z]. Here z stands for t^n (or for T); elements free of z are elements of K.

# Data conventions
* An operator h ∈ O is an Oscar PBW element, read with `pbw_terms(h)`: a list of
  (c, b, a) meaning c Y^b T^a.
* A power series v(Y) is its coefficient vector, `v[k+1] = [Y^k] v`.
* Operators act on series only through  [Y^k](c Y^b T^a · v) = c t^(a(k-b)) v_(k-b)
  (`ycoeff`).

# Workflow (`attempt`)
S(Δ) is the value at Y = 1 of the marginal series C = Σ c_n Y^n; the tests use C
and its partial sums β_n, never the realization that produced them.

0. `readings`: S is additive over the diagonal blocks of the system (`blocks`), and
   each block can be replaced by another system with the same S: its X-marginal
   (`transpose_system`), or the X-marginal of a canonical 1×1 system for its C
   (`canonical`); a block may also be multiplied by a power of Y (`aligned`).
   Steps 1–4 run on the system as given, then on every combination of readings.
1. `solve_series`, `marginal_coeffs`: the coefficients c_n and β_n = c_0 + … + c_n.
   `nonzero_witness`: some β_n below the a-priori rate proves S(Δ) ≠ 0.
2. `annihilator`: an operator H ≠ 0 with H·C = g, a polynomial, found by linear
   algebra over K(T); for several blocks, a least common left multiple (`lclm`).
3. If g = 0, C ≡ 0 is decided exactly from finitely many c_n (`exceptional_set`).
   This covers every comparison of two readings with the same series.
   `reduce_annihilator`: C itself may satisfy an equation A·C = gA of lower order
   (a right factor A of H); A is guessed from the c_n and proved (`check_factor`).
4. `rational_certificate`: R(T) ∈ K(T) with 1 = (1 − Y)P + R·A, from a scalar
   q-difference equation (Abramov's denominator bound, then linear algebra). Without
   a pole at T = 0 it proves convergence and gives S(Δ) exactly; a pole at T = 0 is
   an inverse shift. `polynomial_certificate` does the same for the system itself,
   with R polynomial.
5. `progression_test`: A(1 − Y) gives a recurrence for β_n (`beta_recurrence`). Its
   section along n = p m + r (`section_recurrence`) is a proven recurrence for
   x_m = β_(pm+r). Its q-hypergeometric solutions (`qhyper`) are the channels.
   x is written as Σ a_i G_i(m) from finitely many values (a proof, by the
   recurrence), similar channels are merged (`merge_similar`), and each channel
   either decays or cancels against a partner (`dilation_witness`).
6. `remainder_test`: if no section of β is a sum of channels, each block is
   treated separately, and its β may also be written as channels plus a
   remainder that tends to 0: the channels are hypergeometric elements of the
   module generated by β (`hyper_elements`, from the adjoint recurrence), with
   Laurent coefficients fitted so that the remainder converges (`remainder_fit`).
"""
module QuantumWZ

using Oscar

export setup, compile, attempt, automaton, automata, difference, transpose_system, readings, euler, x_minus_y, delta_one, incomplete

const INF = typemax(Int) ÷ 4   # valuation of 0

"Time (`time()`) after which the searches stop early; set by `attempt` from `time_limit`."
const DEADLINE = Ref(Inf)

