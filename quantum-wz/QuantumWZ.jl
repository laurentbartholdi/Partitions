"""
    compile(ctx, Q, r, e) -> (L, f, d)

Marginal system of a realization  w Q = r,  Δ = w e  over A. With the maps

    Φ(X^a Y^b) = Y^b T^a     (anti-isomorphism A → O)
    ρ(X^a Y^b) = Y^b         (marginal: X = 1)

it returns  L[j,i] = Φ(Q[i,j]),  f[j] = ρ(r[j]),  d[i] = Φ(e[i]),  so that
m_i = ρ(w_i) solves L·m = f and C = ρ(Δ) = Σ_i d[i]·m_i.
Each f[j] is a polynomial in Y, stored as an operator without T. Entries of Q, r, e
may also be integers or elements of K.
"""
function compile(ctx, Q, r, e)
  Q, r, e = map(ctx.A, Q), map(ctx.A, r), map(ctx.A, e)      # integers, scalars → A
  Φ(q) = operator(ctx, [(c, b, a) for (c, a, b) in pbw_terms(q)])
  ρ(q) = operator(ctx, [(c, b, 0) for (c, _, b) in pbw_terms(q)])
  n = length(r)
  return [Φ(Q[i, j]) for j in 1:n, i in 1:n], map(ρ, r), map(Φ, e)
end

"""
    is_normalized(ctx, L, f, d)

The standing assumption: L ≡ I mod t, and f, d have coefficients regular at t = 0.
"""
function is_normalized(ctx, L, f, d)
  n = length(f)
  L_ok = all(valuation_t(c) >= 1 for j in 1:n, i in 1:n
             for (c, _, _) in pbw_terms(L[j, i] - (i == j ? one(ctx.O) : zero(ctx.O))))
  return L_ok && all(valuation_t(c) >= 0 for h in [f; d] for (c, _, _) in pbw_terms(h))
end

"""
    ycoeff(ctx, h, v, k)

The coefficient [Y^k](h · v) for an operator h and a series v:

    Σ over terms c Y^b T^a of h  of  c t^(a(k-b)) v_(k-b),

where v_j = 0 for j < 0 and for j beyond the stored coefficients.
"""
function ycoeff(ctx, h, v, k)
  s = zero(ctx.K)
  for (c, b, a) in pbw_terms(h)
    j = k - b
    0 <= j < length(v) && (s += c * ctx.t^(a * j) * v[j + 1])
  end
  return s
end

"""
    solve_series(ctx, L, f, N) -> m

The solution of L·m = f as coefficient vectors, m[i][k+1] = [Y^k] m_i for k = 0..N.
Coefficient k of the system reads

    L_0(t^k) m_k = [Y^k] f − (terms involving m_0, …, m_(k-1)),

where L_0 is the Y-free part of L; L_0(t^k) is invertible because L_0 ≡ I mod t.
"""
function solve_series(ctx, L, f, N)
  (; K, t) = ctx
  n = length(f)
  m = [elem_type(K)[] for _ in 1:n]
  for k in 0:N
    foreach(mi -> push!(mi, zero(K)), m)        # m_k = 0 while computing the rest
    M = [zero(K) for _ in 1:n, _ in 1:n]
    rhs = [ycoeff(ctx, f[j], [one(K)], k) - sum(ycoeff(ctx, L[j, i], m[i], k) for i in 1:n) for j in 1:n]
    for j in 1:n, i in 1:n, (c, b, a) in pbw_terms(L[j, i])
      b == 0 && (M[j, i] += c * t^(a * k))
    end
    x = solve_field(K, M, rhs)
    for i in 1:n
      m[i][k + 1] = x[i]
    end
  end
  return m
end

"Coefficients c_n = [Y^n] C of C = Σ_i d[i]·m_i, for n = 0..N (c[n+1] = c_n)."
marginal_coeffs(ctx, d, m) = [sum(ycoeff(ctx, d[i], m[i], k) for i in eachindex(d))
                              for k in 0:length(m[1])-1]

# Modular images, t ↦ τ in GF(PRIME). They only screen and reconstruct guesses
# (`reduce_annihilator`); every result is then checked exactly.
const PRIME = 2305843009213693951            # 2^61 − 1
const T0 = 1_000_003                         # the first evaluation point

"x ∈ K = Q(t) at t = τ ∈ Fp = GF(PRIME) (an error if the denominator vanishes)."
function mod_image(Fp, x, τ = Fp(T0))
  ev(p) = foldr((i, s) -> s * τ + Fp(numerator(coeff(p, i))) * inv(Fp(denominator(coeff(p, i)))),
                0:degree(p); init = zero(Fp))
  return ev(numerator(x)) * inv(ev(denominator(x)))
end

"c_0..c_N at t = τ in Fp: `solve_series` and `marginal_coeffs` over Fp."
function marginal_mod(ctx, L, f, d, N, Fp, τ = Fp(T0))
  img(h) = [(mod_image(Fp, c, τ), b, a) for (c, b, a) in pbw_terms(h)]
  Lm, fm, dm = map(img, L), map(img, f), map(img, d)
  yc(terms, v, k) = sum((c * τ^(a * (k - b)) * v[k - b + 1] for (c, b, a) in terms if 0 <= k - b < length(v));
                        init = zero(Fp))
  n = length(f)
  m = [elem_type(Fp)[] for _ in 1:n]
  for k in 0:N
    M = [sum((c * τ^(a * k) for (c, b, a) in Lm[j, i] if b == 0); init = zero(Fp)) for j in 1:n, i in 1:n]
    rhs = [yc(fm[j], [one(Fp)], k) - sum(yc(Lm[j, i], m[i], k) for i in 1:n) for j in 1:n]
    x = solve_field(Fp, M, rhs)
    x === nothing && error("singular modular image")
    foreach(i -> push!(m[i], x[i]), 1:n)
  end
  return [sum(yc(dm[i], m[i], k) for i in 1:n) for k in 0:N]
end

"a/b ≡ c (mod p) with |a|, b ≤ √(p/2), or `nothing` (rational reconstruction)."
function rational_lift(c, p)
  bound = isqrt(div(p, 2))
  r0, r1, s0, s1 = p, mod(c, p), ZZ(0), ZZ(1)
  while r1 > bound
    q = div(r0, r1)
    r0, r1, s0, s1 = r1, r0 - q * r1, s1, s0 - q * s1
  end
  (iszero(s1) || abs(s1) > bound || gcd(r1, s1) != 1) && return nothing
  return QQ(r1, s1)
end

"P ∈ Fp[x] with coefficients lifted to Q by `rational_lift`, as an element of K; or `nothing`."
function lift_to_K(ctx, P)
  cs = [rational_lift(lift(ZZ, coeff(P, i)), ZZ(PRIME)) for i in 0:degree(P)]
  any(isnothing, cs) && return nothing
  return sum((c * ctx.t^(i - 1) for (i, c) in enumerate(cs)); init = zero(ctx.K))
end

"num/den ≡ P mod M with deg num < k (extended Euclid), den monic and prime to M; or `nothing`."
function poly_ratrec(P, M, k)
  r0, r1, s0, s1 = M, P, zero(M), one(M)
  while degree(r1) >= k
    q, rr = divrem(r0, r1)
    r0, r1, s0, s1 = r1, rr, s1, s0 - q * s1
  end
  (iszero(s1) || !isone(gcd(s1, M))) && return nothing
  c = inv(leading_coefficient(s1))
  return r1 * c, s1 * c
end

"""
    reconstruct_kernel(ctx, Fp, kernel_at, U; Nmax = 512) -> Vector of K-elements, or nothing

The kernel of a matrix over K = Q(t), known to be one-dimensional, from its images:
kernel_at(τ) gives the normalized kernel vector at t = τ in Fp (or `nothing` at a bad
point). Each coordinate, a rational function of t, is found by interpolation at N
points and rational reconstruction (`poly_ratrec`), validated at four more points,
and lifted to Q (`rational_lift`); N doubles up to Nmax. The result is a guess.
"""
function reconstruct_kernel(ctx, Fp, kernel_at, U; Nmax = 512)
  R, x = polynomial_ring(Fp, :x)
  τs, vals = elem_type(Fp)[], Vector{elem_type(Fp)}[]
  next = T0 + 1
  N = 16
  while N <= Nmax
    while length(τs) < N + 4
      τ = Fp(next); next += 1
      v = try kernel_at(τ) catch; nothing end
      v === nothing || (push!(τs, τ); push!(vals, v))
      next > T0 + 4 * Nmax && return nothing
    end
    M = prod(x - τ for τ in τs[1:N])
    fracs = []
    for u in 1:U
      nd = poly_ratrec(interpolate(R, τs[1:N], [v[u] for v in vals[1:N]]), M, cld(N, 2))
      nd === nothing && break
      num, den = nd
      all(evaluate(num, τs[i]) == vals[i][u] * evaluate(den, τs[i]) for i in N+1:N+4) || break
      push!(fracs, nd)
    end
    if length(fracs) == U
      out = elem_type(ctx.K)[]
      for (num, den) in fracs
        a, b = lift_to_K(ctx, num), lift_to_K(ctx, den)
        (a === nothing || b === nothing) && return nothing
        push!(out, a // b)
      end
      return out
    end
    N *= 2
  end
  return nothing
end

"""
    nonzero_witness(ctx, L, f, d, β)

A-priori rate (section "An unconditional rate"): with D = max(1, deg_Y L) and
α = deg_Y f + deg_Y d,

    ν(S(Δ) − β_n) ≥ k(n) = max(0, ⌈(n+1−α)/D⌉).

If ν(β_n) < k(n) for some n, then S(Δ) ≠ 0 and S(Δ) has the same leading term as
β_n. Returns the first such (n, ν(β_n), β_n), or `nothing`.
"""
function nonzero_witness(ctx, L, f, d, β)
  D = max(1, maximum(ydeg, L))
  α = max(0, maximum(ydeg, f)) + max(0, maximum(ydeg, d))
  for n in 0:length(β)-1
    v = valuation_t(β[n + 1])
    v < max(0, cld(n + 1 - α, D)) && return (n, v, β[n + 1])
  end
  return nothing
end

