"""
    factor_over_K(ctx, p) -> [(f, e)]

Irreducible factors over K = Q(t) of p ∈ F, a polynomial in z with denominator
free of z: the numerator is factored in Q[t, z] (Flint), factors free of z
(constants of K) are dropped, and each factor is made monic in z.
"""
function factor_over_K(ctx, p)
  out = Tuple{elem_type(ctx.F), Int}[]
  for (q, e) in factor(numerator(p))
    degree(q, 2) <= 0 && continue
    f = ctx.F(q)
    push!(out, (f // zcoeffs(ctx, f)[end], e))
  end
  return out
end

"The nonzero roots in K of Σ_i cs[i] W^(i−1) (from its linear factors over K)."
function roots_in_K(ctx, cs)
  nz = findall(!iszero, cs)
  length(nz) == 2 && nz[2] == nz[1] + 1 && return [-cs[nz[1]] // cs[nz[2]]]   # binomial: no factoring
  pol = from_zcoeffs(ctx, cs)
  zdeg(pol) < 1 && return elem_type(ctx.F)[]
  roots = [-zcoeffs(ctx, f)[1] for (f, _) in factor_over_K(ctx, pol) if zdeg(f) == 1]
  return filter(!iszero, roots)
end

"a(z) = b(t^h z) up to a constant, for some h ≥ 0 (a, b monic in z)."
function related(ctx, a, b)
  zdeg(a) == zdeg(b) || return false
  for h in 0:63
    bh = zsub(ctx, b, h)
    bh // zcoeffs(ctx, bh)[end] == a && return true
  end
  return false
end

"Lowest z-exponent, its coefficient, z-degree and leading coefficient of a polynomial in z."
function extremes(ctx, f)
  cs = zcoeffs(ctx, f)
  lo = findfirst(!iszero, cs)
  return lo - 1, cs[lo], length(cs) - 1, cs[end]
end

"""
    qhyper(ctx, q) -> ratios

Ratios g ∈ F of the q-hypergeometric solutions of Σ_(i=0..k) q_i(z) x_(m+i) = 0
(z = t^m), that is x_(m+1) = g(t^m) x_m. Following Abramov–Paule–Petkovšek, write
g = Z·A(z)/B(z)·C(tz)/C(z) with A | q_0 and B | q_k(t^(1−k) z) monic, and
gcd(A(z), B(t^h z)) = 1 for h ≥ 0. Then

    Σ_i Z^i T_i(z) C(t^i z) = 0,   T_i = q_i Π_(j<i) A(t^j z) Π_(i≤j<k) B(t^j z).

The lowest z-coefficients give an equation for Z, and the highest ones an
equation for W = Z t^(deg C). Both need only the extreme coefficients of the T_i,
so most candidates (A, B) are rejected without building any polynomial. For
each surviving (Z, deg C), C is a kernel vector of a linear system over K. Every
returned g is verified to solve the recurrence. The number of candidates (A, B)
is the product of (multiplicity + 1) over the factors; above `max_candidates`
nothing is returned (a search bound, like the period bound). The search also stops
at `DEADLINE`.
"""
function qhyper(ctx, q; max_candidates = 50_000)
  (; F, tF, zF) = ctx
  k = length(q) - 1
  time() > DEADLINE[] && return elem_type(F)[]
  fa = factor_over_K(ctx, q[1])
  fb = factor_over_K(ctx, zsub(ctx, q[k + 1], 1 - k))
  prod(e + 1 for (_, e) in [fa; fb]; init = 1) > max_candidates && return elem_type(F)[]
  ea = [extremes(ctx, f) for (f, _) in fa]
  eb = [extremes(ctx, f) for (f, _) in fb]
  eq = [iszero(x) ? nothing : extremes(ctx, x) for x in q]
  function combine(ext, exps)               # extremes of a product of factors
    lo, c0, dg, c1 = 0, one(F), 0, one(F)
    for ((l, a0, d_, a1), e) in zip(ext, exps)
      lo += e * l; c0 *= a0^e; dg += e * d_; c1 *= a1^e
    end
    return lo, c0, dg, c1
  end
  found = elem_type(F)[]
  for expA in Iterators.product((0:e for (_, e) in fa)...), expB in Iterators.product((0:e for (_, e) in fb)...)
    time() > DEADLINE[] && break
    lA, cA, dA, hA = combine(ea, expA)
    lB, cB, dB, hB = combine(eb, expB)
    low = Dict{Int, Any}(); top = Dict{Int, Any}()
    for i in 0:k
      eq[i + 1] === nothing && continue
      lq, cq, dq, hq = eq[i + 1]
      cl, ch = cq, hq
      for j in 0:i-1
        cl *= cA * tF^(j * lA); ch *= hA * tF^(j * dA)
      end
      for j in i:k-1
        cl *= cB * tF^(j * lB); ch *= hB * tF^(j * dB)
      end
      low[i] = (lq + i * lA + (k - i) * lB, cl)
      top[i] = (dq + i * dA + (k - i) * dB, ch)
    end
    dl = minimum(first, values(low)); dh = maximum(first, values(top))
    lowc = [haskey(low, i) && low[i][1] == dl ? low[i][2] : zero(F) for i in 0:k]
    topc = [haskey(top, i) && top[i][1] == dh ? top[i][2] : zero(F) for i in 0:k]
    (count(!iszero, lowc) < 2 || count(!iszero, topc) < 2) && continue
    Afs = [f for ((f, _), e) in zip(fa, expA) if e > 0]
    Bfs = [f for ((f, _), e) in zip(fb, expB) if e > 0]
    any(related(ctx, a, b) for a in Afs for b in Bfs) && continue
    Zs = roots_in_K(ctx, lowc)
    isempty(Zs) && continue
    cand = Tuple{elem_type(F), Int}[]              # (Z, deg C) with W = Z t^(deg C)
    for Z in Zs, W in roots_in_K(ctx, topc)
      e = tval(W // Z)
      0 <= e <= 64 && W // Z == tF^e && push!(cand, (Z, e))
    end
    isempty(cand) && continue
    A_ = prod((f^e for ((f, _), e) in zip(fa, expA)); init = one(F))
    B_ = prod((f^e for ((f, _), e) in zip(fb, expB)); init = one(F))
    T_ = [q[i + 1] * prod((zsub(ctx, A_, j) for j in 0:i-1); init = one(F)) *
                     prod((zsub(ctx, B_, j) for j in i:k-1); init = one(F)) for i in 0:k]
    for (Z, e) in unique(cand)
      cols = [zcoeffs(ctx, sum(Z^i * T_[i + 1] * tF^(i * l) for i in 0:k) * zF^l) for l in 0:e]
      M = [j <= length(cols[l + 1]) ? cols[l + 1][j] : zero(F)
           for j in 1:maximum(length, cols), l in 0:e]
      for x in kernel_field(ctx.K, over_K(ctx, M))
        C = from_zcoeffs(ctx, [toF(ctx, y) for y in x])
        iszero(C) && continue
        g = Z * A_ // B_ * zsub(ctx, C, 1) // C
        g in found || !satisfies(ctx, q, g) || push!(found, g)
      end
    end
  end
  return found
end

"Does x_(m+1) = g(t^m) x_m solve Σ_i q_i(t^m) x_(m+i) = 0?  (an identity in F)"
function satisfies(ctx, q, g)
  acc, prodg = zero(ctx.F), one(ctx.F)
  for i in eachindex(q)
    acc += q[i] * prodg
    prodg *= zsub(ctx, g, i - 1)
  end
  return iszero(acc)
end

