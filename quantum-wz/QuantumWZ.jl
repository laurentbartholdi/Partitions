"ν(g(t^j)) for g ∈ F, or `nothing` if g(t^j) is 0 or ∞."
function val_at(ctx, g, j)
  a = tval(at_tk(ctx, ctx.F(numerator(g)), j))
  b = tval(at_tk(ctx, ctx.F(denominator(g)), j))
  return (a == INF || b == INF) ? nothing : a - b
end

"""
    poly_profile(ctx, p) -> (i0, v0, J)

For 0 ≠ p = Σ p_i z^i (a polynomial in z over K) with least exponent i0 and
v0 = ν(p_i0): the term i0 has the strictly smallest valuation at z = t^j as soon
as j (i − i0) > v0 − ν(p_i) for every other term i. Hence ν(p(t^j)) = i0 j + v0,
and p(t^j) ≠ 0, for all j ≥ J.
"""
function poly_profile(ctx, p)
  terms = [(i - 1, tval(c)) for (i, c) in enumerate(zcoeffs(ctx, p)) if !iszero(c)]
  i0, v0 = terms[1]
  J = maximum((fld(v0 - v, i - i0) + 1 for (i, v) in terms[2:end]); init = 0)
  return i0, v0, J
end

"For 0 ≠ g ∈ F: ν(g(t^j)) = σ j + τ for all j ≥ J."
function val_profile(ctx, g)
  i1, v1, J1 = poly_profile(ctx, ctx.F(numerator(g)))
  i2, v2, J2 = poly_profile(ctx, ctx.F(denominator(g)))
  return i1 - i2, v1 - v2, max(J1, J2)
end

"min over j ≥ j0 of ν(g(t^j)) (−INF if unbounded below), or `nothing` if g = 0 or g(t^j) ∈ {0, ∞} for some j ≥ j0."
function min_val(ctx, g, j0)
  iszero(g) && return nothing
  σ, τ, J = val_profile(ctx, g)
  J = max(J, j0)
  vals = [val_at(ctx, g, j) for j in j0:J-1]
  any(isnothing, vals) && return nothing
  σ < 0 && return -INF
  return minimum(Int[vals; σ * J + τ])
end

"The least m1 ≥ j0 such that g(t^j) is finite and nonzero for all j ≥ m1."
function first_regular(ctx, g, j0)
  J = max(val_profile(ctx, g)[3], j0)
  m1 = j0
  for j in j0:J-1
    val_at(ctx, g, j) === nothing && (m1 = j + 1)
  end
  return m1
end

"""
    dilation_witness(ctx, θ, λ, μ = 0)

Search χ, a polynomial in ζ (written z) with χ(0) = 1, such that

    θ(ζ) χ(ζ) = ∏_(i=0..λ−1) χ(t^(μ+i) ζ^λ),

with integral coefficients and χ(1) ≠ 0 (section "Finding the witness"). The
offset μ allows products that start later (an index shift by s gives μ = s(λ−1)).
Writing θ = u/v: u(0) = v(0) and (λ² − 1) deg χ = deg u − deg v. The coefficient of
ζ^j in v·∏χ(t^(μ+i) ζ^λ) − u·χ is −u(0) χ_j plus terms in χ_0..χ_(j−1), so χ is
determined degree by degree; the identity is then checked. Returns (χ, i1, c) with
ν(χ(t^j) − 1) ≥ i1·j + c for j ≥ 0, or `nothing`.
"""
function dilation_witness(ctx, θ, λ, μ = 0)
  (; F, zF) = ctx
  u, v = F(numerator(θ)), F(denominator(θ))
  u0, v0 = zcoeffs(ctx, u)[1], zcoeffs(ctx, v)[1]
  (iszero(u0) || u0 != v0) && return nothing
  e = zdeg(u) - zdeg(v)
  (e < 0 || e % (λ^2 - 1) != 0) && return nothing
  dilate(χ) = prod(zsub(ctx, χ, μ + i, λ) for i in 0:λ-1)
  χ = one(F)
  for j in 1:e ÷ (λ^2 - 1)
    cs = zcoeffs(ctx, v * dilate(χ) - u * χ)
    χ += (j < length(cs) ? cs[j + 1] : zero(F)) // u0 * zF^j
  end
  v * dilate(χ) == u * χ || return nothing
  terms = [(i - 1, tval(c)) for (i, c) in enumerate(zcoeffs(ctx, χ)) if i > 1 && !iszero(c)]
  (any(c < 0 for (_, c) in terms) || iszero(at_tk(ctx, χ, 0))) && return nothing
  isempty(terms) && return (χ, 1, 0)
  return (χ, minimum(first, terms), minimum(last, terms))
end

"A dilation witness (λ, μ, χ, i1, c) for θ, any admissible λ ≥ 2 ((λ² − 1) | deg u − deg v) and |μ| ≤ 6."
function dilation(ctx, θ; μs = -6:6)
  e = zdeg(ctx.F(numerator(θ))) - zdeg(ctx.F(denominator(θ)))
  λ = 2
  while λ^2 - 1 <= e
    for μ in μs
      w = dilation_witness(ctx, θ, λ, μ)
      w === nothing || return (λ, μ, w...)
    end
    λ += 1
  end
  return nothing
end

"""
    shift_forms(ctx, θ) -> [(θw, Γ)]

Rewritings θ(ζ) = θw(ζ) Γ(tζ)/Γ(ζ) with Γ(0) = 1, to be tried for dilation witnesses.
The first is θ itself (Γ = 1). In the others every irreducible factor f of θ,
normalized to f(0) = 1, is replaced by the shift f(t^s ζ) whose lowest nonconstant
coefficient, at ζ^e, has valuation in [w, w + e), for windows w = 0..3. Shift-related
factors of numerator and denominator then cancel. A factor f(ζ) of the numerator
shifted by s contributes Γ = ∏_(i=1..−s) f(t^(−i) ζ) (s < 0) or ∏_(i=0..s−1) 1/f(t^i ζ)
(s > 0), so that ∏_(j=m1..m−1) θ(t^j) = Γ(t^m)/Γ(t^m1) · ∏_(j=m1..m−1) θw(t^j).
"""
function shift_forms(ctx, θ)
  (; F) = ctx
  out = [(θ, one(F))]
  parts = [[(f, e) for (f, e) in factor_over_K(ctx, F(numerator(θ)))];
           [(f, -e) for (f, e) in factor_over_K(ctx, F(denominator(θ)))]]
  any(iszero(zcoeffs(ctx, f)[1]) for (f, _) in parts) && return out
  c0 = zcoeffs(ctx, F(numerator(θ)))[1] // zcoeffs(ctx, F(denominator(θ)))[1]
  for w in 0:3
    θw, Γ = c0, one(F)
    for (f, e) in parts
      f = f // zcoeffs(ctx, f)[1]                               # f(0) = 1
      cs = zcoeffs(ctx, f)
      e0 = findfirst(!iszero, cs[2:end])                        # lowest nonconstant exponent
      s = cld(w - tval(cs[e0 + 1]), e0)
      Γf = s < 0 ? prod(zsub(ctx, f, -i) for i in 1:-s) :
           s > 0 ? inv(prod(zsub(ctx, f, i) for i in 0:s-1)) : one(F)
      θw *= e > 0 ? zsub(ctx, f, s)^e : inv(zsub(ctx, f, s))^(-e)
      Γ *= e > 0 ? Γf^e : inv(Γf)^(-e)
    end
    any(x -> x[1] == θw, out) || push!(out, (θw, Γ))
  end
  return out
end

"""
    channel_proof(ctx, gs, a, m1)

Prove ν(x_m) → ∞ for x_m = Σ_i a_i G_i(m), G_i(m1) = 1, G_i(m+1) = g_i(t^m) G_i(m).
Every channel with a_i ≠ 0 must satisfy ν(g_i(t^j)) ≥ 0 for j ≥ m1. Then:

* decaying channels (ν(g_i(t^j)) ≥ 1 eventually) satisfy ν(a_i G_i(m)) ≥ m + κ;
* the remaining (stationary) channels must cancel in pairs (k1, k2): θ = g_k2/g_k1 is
  written as θw(ζ) Γ(tζ)/Γ(ζ) (`shift_forms`), θw has a dilation witness (λ, μ, χ),
  and a_k2/a_k1 = −F(m1) Γ(t^m1), where F(m) = ∏_(l=m..λm+μ−1) χ(t^l). Since
  F(m+1)/F(m) = θw(t^m), we get a_k1 G_k1(m) + a_k2 G_k2(m) =
  a_k1 G_k1(m) (1 − F(m) Γ(t^m)), of valuation ≥ slope·m + κ (Γ(0) = 1).

Returns (; slope, κ, parts): ν(x_m) ≥ slope·m + κ for m ≥ m1, or `nothing`.
"""
function channel_proof(ctx, gs, a, m1)
  decay, stationary = [], Int[]
  for i in eachindex(gs)
    iszero(a[i]) && continue
    lo = min_val(ctx, gs[i], m1)
    (lo === nothing || lo < 0) && return nothing
    σ, τ, J = val_profile(ctx, gs[i])
    if σ > 0 || τ >= 1
      M = σ > 0 ? max(J, m1, cld(1 - τ, σ)) : max(J, m1)
      push!(decay, (; kind = :decay, channel = i, slope = 1, κ = tval(a[i]) - M))
    else
      push!(stationary, i)
    end
  end
  function pair_up(rest)                        # pairs of stationary channels, or nothing
    isempty(rest) && return []
    i1 = rest[1]
    for i2 in rest[2:end], (k1, k2) in ((i1, i2), (i2, i1)), (θw, Γ) in shift_forms(ctx, gs[k2] // gs[k1])
      w = dilation(ctx, θw)
      w === nothing && continue
      λ, μ, χ, slope, c = w
      λ * m1 + μ >= m1 || continue
      θw * zsub(ctx, Γ, 1) == gs[k2] // gs[k1] * Γ || continue     # θ = θw Γ(tζ)/Γ(ζ)
      first_regular(ctx, Γ, m1) == m1 || continue                  # Γ(t^j) ≠ 0, ∞ for j ≥ m1
      Fm1 = prod((at_tk(ctx, χ, l) for l in m1:λ*m1+μ-1); init = one(ctx.F))
      a[k2] // a[k1] == -Fm1 * at_tk(ctx, Γ, m1) || continue
      if !isone(Γ)                                                 # ν(Γ(t^m) − 1) ≥ slope·m + c
        σ, τ, J = val_profile(ctx, Γ - 1)
        slope = min(slope, σ)
        J = max(J, m1)
        vs = [val_at(ctx, Γ - 1, j) for j in m1:J-1]
        c = minimum(Int[c; (σ - slope) * J + τ; [v - slope * j for (j, v) in zip(m1:J-1, vs) if v !== nothing]])
      end
      more = pair_up(filter(x -> x != i1 && x != i2, rest))
      more === nothing && continue
      return pushfirst!(more, (; kind = :dilation, channels = (k1, k2), λ, μ, χ, Γ, slope, κ = tval(a[k1]) + c))
    end
    return nothing
  end
  pairs = pair_up(stationary)
  pairs === nothing && return nothing
  parts = [decay; pairs]
  isempty(parts) && return (; slope = 1, κ = INF, parts)
  return (; slope = minimum(x.slope for x in parts), κ = minimum(x.κ for x in parts), parts)
end

"""
    shift_of(ctx, f, f2) -> s or nothing

The integer s with f2(z) = f(t^s z) up to a constant (f, f2 irreducible and monic in z).
"""
function shift_of(ctx, f, f2; smax = 64)
  zdeg(f) == zdeg(f2) || return nothing
  for s in -smax:smax
    g = zsub(ctx, f, s)
    g // zcoeffs(ctx, g)[end] == f2 && return s
  end
  return nothing
end

"""
    similarity(ctx, ρ) -> h or nothing

h ∈ F with h(tz)/h(z) = ρ, if it exists (then two terms with ratios g and g·ρ differ
by the rational factor h(t^m)). Factor ρ and group its irreducible factors into
classes {f(t^s z)}: h(tz)/h(z) contributes +1 at f(t^(s+1) z) and −1 at f(t^s z), so
every class must have total exponent 0, and then h = ∏_s f(t^s z)^(w_s) with
w_s = −(sum of the exponents at shifts ≤ s). A remaining constant t^k is absorbed by
z^k. The identity is checked at the end.
"""
function similarity(ctx, ρ)
  (; F, tF, zF) = ctx
  isone(ρ) && return one(F)
  facs = [[(f, e) for (f, e) in factor_over_K(ctx, F(numerator(ρ)))];
          [(f, -e) for (f, e) in factor_over_K(ctx, F(denominator(ρ)))]]
  any(zdeg(f) == 1 && iszero(zcoeffs(ctx, f)[1]) for (f, _) in facs) && return nothing
  classes = Tuple{elem_type(F), Dict{Int, Int}}[]
  for (f, e) in facs
    placed = false
    for (f0, ex) in classes
      s = shift_of(ctx, f0, f)
      s === nothing && continue
      ex[s] = get(ex, s, 0) + e
      placed = true
      break
    end
    placed || push!(classes, (f, Dict(0 => e)))
  end
  h = one(F)
  for (f0, ex) in classes
    sum(values(ex)) == 0 || return nothing
    acc = 0
    for s in minimum(keys(ex)):maximum(keys(ex))
      acc += get(ex, s, 0)
      acc == 0 && continue
      fs = zsub(ctx, f0, s)
      h *= acc > 0 ? inv(fs)^acc : fs^(-acc)
    end
  end
  c = ρ // (zsub(ctx, h, 1) // h)
  k = tval(c)
  c == (k >= 0 ? tF^k : inv(tF)^(-k)) || return nothing
  h *= k >= 0 ? zF^k : inv(zF)^(-k)
  return zsub(ctx, h, 1) // h == ρ ? h : nothing
end

"""
    merge_similar(ctx, gs, a, m1) -> ratios

One channel per similarity class. If g_j = g_i·h(tz)/h(z), then G_j(m) = G_i(m)·
h(t^m)/h(t^m1), so the class contributes P(t^m) G_i(m) with
P = Σ_j a_j h_j(z)/h_j(t^m1); this is a single q-hypergeometric term with ratio
g_i·P(tz)/P(z). Classes with P = 0 disappear.
"""
function merge_similar(ctx, gs, a, m1)
  classes = []                                  # (representative i, [(j, h_j)])
  for j in eachindex(gs)
    iszero(a[j]) && continue
    placed = false
    for (i, members) in classes
      h = similarity(ctx, gs[j] // gs[i])
      h === nothing && continue
      push!(members, (j, h))
      placed = true
      break
    end
    placed || push!(classes, (j, Any[(j, one(ctx.F))]))
  end
  merged = elem_type(ctx.F)[]
  for (i, members) in classes
    Pc = sum(a[j] * h // at_tk(ctx, h, m1) for (j, h) in members)
    iszero(Pc) || push!(merged, gs[i] * zsub(ctx, Pc, 1) // Pc)
  end
  return merged
end

"""
    decompose(ctx, q, gs, xval, m0) -> (m1, a) or nothing

Coefficients with x_m = Σ_i a_i G_i(m) for all m ≥ m1 (Proposition "decomposition"):
m1 ≥ m0 is past the zeros and poles of q_k and of the ratios, G_i(m1) = 1, and the
identity is imposed on the k = ord(q) values m1, …, m1 + k − 1.
"""
function decompose(ctx, q, gs, xval, m0)
  (; F) = ctx
  k = length(q) - 1
  m1 = maximum([m0; first_regular(ctx, q[end], m0); [first_regular(ctx, gg, m0) for gg in gs]])
  G = [accumulate(*, [one(F); [at_tk(ctx, gg, l) for l in m1:m1+k-2]]) for gg in gs]
  M = [G[i][j] for j in 1:k, i in eachindex(gs)]
  a = solve_field(ctx.K, over_K(ctx, M), [xval(m1 + j) for j in 0:k-1])
  a === nothing && return nothing
  return m1, [toF(ctx, y) for y in a]
end

"""
    progression_test(ctx, p, kreg, β, per, r)

The channel test along n = per·m + r, where β(n) returns β_n and the recurrence p
holds for n ≥ kreg: the proven recurrence q of x_m = β_(per·m+r)
(`section_recurrence`), its q-hypergeometric solutions (`qhyper`), the decomposition
of x, one channel per similarity class (`merge_similar`), and `channel_proof`.
"""
function progression_test(ctx, p, kreg, β, per, r)
  q = section_recurrence(ctx, p, per, r)       # order k ≥ 1
  (q === nothing || iszero(q[1])) && return nothing
  k = length(q) - 1
  m0 = max(0, cld(kreg - r, per))
  xval = m -> β(per * m + r)
  gs = qhyper(ctx, q)
  isempty(gs) && return nothing
  dec = decompose(ctx, q, gs, xval, m0)
  dec === nothing && return nothing
  gs = merge_similar(ctx, gs, dec[2], dec[1])
  isempty(gs) && return (; period = per, residue = r, m1 = dec[1], order = k,
                           ratios = gs, coeffs = [], slope = 1, κ = INF, parts = [])
  all(satisfies(ctx, q, gg) for gg in gs) || return nothing
  dec = decompose(ctx, q, gs, xval, m0)
  dec === nothing && return nothing
  m1, a = dec
  proof = channel_proof(ctx, gs, a, m1)
  proof === nothing && return nothing
  return (; period = per, residue = r, m1, order = k, ratios = gs, coeffs = a, proof...)
end

# =============================================================================
# 8. Channels up to a convergent remainder   (section "Hypergeometric elements")
# =============================================================================

"z^e ∈ F for any integer e."
zpow(ctx, e) = e >= 0 ? ctx.zF^e : inv(ctx.zF)^(-e)

"Order at z = 0 of g ∈ F (INF for g = 0)."
zorder(ctx, g) = iszero(g) ? INF :
  extremes(ctx, ctx.F(numerator(g)))[1] - extremes(ctx, ctx.F(denominator(g)))[1]

"""
    laurent(ctx, g, lo, hi) -> [[z^e] g for e = lo..hi]

Laurent coefficients at z = 0 of g ∈ F (elements of F free of z): with
denominator z^v D(z), D(0) ≠ 0, the series of numerator/D by forward substitution.
"""
function laurent(ctx, g, lo, hi)
  (; F) = ctx
  iszero(g) && return [zero(F) for _ in lo:hi]
  ncs, dcs = zcoeffs(ctx, F(numerator(g))), zcoeffs(ctx, F(denominator(g)))
  v = findfirst(!iszero, dcs) - 1
  dt = dcs[v+1:end]
  s = elem_type(F)[]
  for i in 0:hi+v
    acc = i < length(ncs) ? ncs[i + 1] : zero(F)
    for j in 1:min(i, length(dt) - 1)
      acc -= dt[j + 1] * s[i - j + 1]
    end
    push!(s, acc // dt[1])
  end
  return [0 <= e + v <= hi + v ? s[e + v + 1] : zero(F) for e in lo:hi]
end

"""
    hyper_elements(ctx, q) -> [(; ω, γ, ℓ)]

Hypergeometric elements of the module generated by a solution x of the recurrence
(𝒬x)_m = Σ_(i=0..k) q_i(t^m) x_(m+i) = 0: combinations w_m = Σ_(j=1..k) ℓ_j(t^m) x_(m+j)
with w_(m+1) = ω(t^m) w_m. They come from the hypergeometric solutions y, with ratio γ, of
the adjoint recurrence (𝒬*y)_m = Σ_i q_i(t^(m−i)) y_(m−i) = 0 (`qhyper` applied to
q*_i(z) = q_(k−i)(t^i z)). The concomitant

    W_m = Σ_(i=1..k) Σ_(l=m−i+1..m) q_i(t^l) y_l x_(l+i)

satisfies W_m − W_(m−1) = y_m (𝒬x)_m − x_m (𝒬*y)_m = 0, so w = W/y with

    ℓ_j(z) = Σ_(i=j..k) q_i(t^(j−i) z) ∏_(u=1..i−j) γ(t^(−u) z)^(−1),   ω = 1/γ.

Each ℓ is scaled by a power z^(−v) (so that its least order at z = 0 is 0), which
multiplies ω by t^(−v).
"""
function hyper_elements(ctx, q)
  (; F, tF) = ctx
  k = length(q) - 1
  out = []
  for γ in qhyper(ctx, [zsub(ctx, q[k - i + 1], i) for i in 0:k])
    ℓ = [sum(zsub(ctx, q[i + 1], j - i) * prod((inv(zsub(ctx, γ, -u)) for u in 1:i-j); init = one(F))
             for i in j:k) for j in 1:k]
    all(iszero, ℓ) && continue
    v = minimum(zorder(ctx, x) for x in ℓ)
    push!(out, (; ω = inv(γ) * (v <= 0 ? tF^(-v) : inv(tF)^v), γ, ℓ = [x * zpow(ctx, -v) for x in ℓ]))
  end
  return out
end

"""
    remainder_fit(ctx, els, q; Emax = 6) -> (s, ρ) or nothing

Laurent polynomials s_i (one per element, pole order ≤ E at z = 0) and ρ such that

    Π = 1 − Σ_i s_i(z) Σ_(j=1..k) ℓ_(i,j)(z) E^j + ρ(z) Σ_(j=0..k) q_j(z) E^j = Σ_(j=0..k) π_j(z) E^j

has every π_j regular at z = 0 and Σ_j π_j(0) = 0. Then x_m = Σ_i s_i(t^m) w_(i,m) + (Πx)_m
for m ≥ m0, and (Πx)_m → 0 (`remainder_test`). The conditions are linear in the Laurent
coefficients. E runs from 0 to Emax; then elements are dropped one at a time while the
conditions stay solvable, so that few channels remain.
"""
function remainder_fit(ctx, els, q; Emax = 6)
  (; K, F) = ctx
  k = length(q) - 1
  vq = minimum(zorder(ctx, x) for x in q)
  gens = [[[zero(F)]; [-x for x in e.ℓ]] for e in els]
  push!(gens, [x * zpow(ctx, -vq) for x in q])                  # ρ (scaled; ρ absorbs z^vq)
  ρg = length(gens)
  function fit(use, E)
    lc = Dict((g, j) => laurent(ctx, gens[g][j + 1], 0, E) for g in use for j in 0:k)
    cf(g, j, e) = 0 <= e <= E ? lc[(g, j)][e + 1] : zero(F)
    cols = [(g, e) for e in -E:0 for g in use]
    rows = [[cf(g, j, e1 - e) for (g, e) in cols] for j in 0:k for e1 in -E:-1]
    push!(rows, [sum(cf(g, j, -e) for j in 0:k) for (g, e) in cols])
    rhs = [[zero(F) for _ in 1:length(rows)-1]; -one(F)]
    x = solve_field(K, over_K(ctx, [r[c] for r in rows, c in eachindex(cols)]), over_K(ctx, rhs))
    x === nothing && return nothing
    return [sum((toF(ctx, x[u]) * zpow(ctx, e) for (u, (gg, e)) in enumerate(cols) if gg == g); init = zero(F))
            for g in eachindex(gens)]
  end
  use = collect(eachindex(gens))
  E = findfirst(E -> fit(use, E) !== nothing, 0:Emax)
  E === nothing && return nothing
  E -= 1
  for i in 1:ρg-1                                                # drop elements while possible
    rest = filter(!=(i), use)
    fit(rest, E) === nothing || (use = rest)
  end
  s = fit(use, E)
  π = [(j == 0 ? one(F) : zero(F)) + sum(s[g] * gens[g][j + 1] for g in eachindex(gens)) for j in 0:k]
  @assert all(zorder(ctx, x) >= 0 for x in π) && iszero(sum(laurent(ctx, x, 0, 0)[1] for x in π))
  return s[1:end-1], s[end] * zpow(ctx, -vq)
end

"""
    restrict(ctx, ch, per, r) -> channels along n = per·m + r

Channels found for n itself (x_n = Σ a_i G_i(n), up to a remainder → 0, for n ≥ n1)
along the progression: G_i(per·m + r) has the ratio ∏_(l<per) g_i(t^(r+l) z^per) in m,
and the coefficients become a_i G_i(per·m1 + r), m1 the least m with per·m + r ≥ n1.
"""
function restrict(ctx, ch, per, r)
  per == 1 && r == 0 && return ch
  m1 = max(0, cld(ch.m1 - r, per))
  n1 = per * m1 + r
  ratios = [prod(zsub(ctx, g, r + l, per) for l in 0:per-1) for g in ch.ratios]
  coeffs = [a * prod((at_tk(ctx, g, l) for l in ch.m1:n1-1); init = one(ctx.F)) for (g, a) in zip(ch.ratios, ch.coeffs)]
  return (; ch..., ratios, coeffs, m1)
end

"Coefficients at m1′ ≥ m1 of channels normalized at m1 (G_i(m1) = 1)."
renormalize(ctx, gs, a, m1, m1′) =
  [a[i] * prod((at_tk(ctx, gs[i], l) for l in m1:m1′-1); init = one(ctx.F)) for i in eachindex(gs)]

"""
    merge_channels(ctx, gs, a, m1) -> (gs, a, m1)

One channel per similarity class, with its coefficient (as in `merge_similar`): after
moving m1 to m0, past the zeros and poles of the h_j (g_j = g_i h_j(tz)/h_j(z)), the
class of g_i contributes G_i(m) P(t^m), P = Σ_j a_j h_j(z)/h_j(t^m0), a channel with
ratio g_i P(tz)/P(z) and coefficient P(t^m0). Classes with P = 0 disappear; m0 moves
past the zeros and poles of the merged ratios, and the coefficients are renormalized.
"""
function merge_channels(ctx, gs, a, m1)
  classes = []
  for j in eachindex(gs)
    iszero(a[j]) && continue
    h = nothing
    k = findfirst(c -> (h = similarity(ctx, gs[j] // gs[c[1]])) !== nothing, classes)
    k === nothing ? push!(classes, (j, Any[(j, one(ctx.F))])) : push!(classes[k][2], (j, h))
  end
  m0 = maximum([m1; [first_regular(ctx, h, m1) for (_, ms) in classes for (_, h) in ms]])
  a = renormalize(ctx, gs, a, m1, m0)                  # past the zeros and poles of the h_j
  out_g, out_a = elem_type(ctx.F)[], elem_type(ctx.F)[]
  for (i, members) in classes
    P = sum(a[j] * h // at_tk(ctx, h, m0) for (j, h) in members)
    iszero(P) && continue
    push!(out_g, gs[i] * zsub(ctx, P, 1) // P)
    push!(out_a, at_tk(ctx, P, m0))
  end
  m1′ = maximum([m0; [first_regular(ctx, g, m0) for g in out_g]])
  return out_g, renormalize(ctx, out_g, out_a, m0, m1′), m1′
end

"""
    block_reading(ctx, name, B; N = 30) -> Reading, or nothing

The data of one block system B = (L, f, d) for `block_channels`: its coefficients, the
least annihilator of its marginal (`annihilator`, `reduce_annihilator`), and the
recurrence of its β (`beta_recurrence`).
"""
function block_reading(ctx, name, B; N = 30)
  L, f, d = B
  rd = Reading((name,), L, f, d, [B], marginal_coeffs(ctx, d, solve_series(ctx, L, f, N)), [], 0)
  H, R = annihilator(ctx, L, f, d)
  g = ε(ctx, sum(R[j] * f[j] for j in eachindex(f)))
  cn(n) = n < 0 ? zero(ctx.K) : coeffs_upto!(ctx, rd, n)[n + 1]
  A, gA = reduce_annihilator(ctx, H, g, B, cn)
  p, k0 = beta_recurrence(ctx, A, gA)
  rd.p, rd.kreg = p, first_regular(ctx, p[end], k0)
  return rd
end

"""
    block_channels(ctx, bd, per, r, approx) -> (; exact, ratios, coeffs, m1, …) or nothing

The β of one block along n = per·m + r as channels: exactly, x = Σ a_i G_i
(`qhyper`, `decompose`), or up to a remainder that tends to 0 (`hyper_elements`,
`remainder_fit`): x_m = Σ_i s_i(t^m) w_(i,m) + (Πx)_m, the channels being s_i w_i. The
remainder fit is tried first for n itself (cached in `approx`) and restricted to the
progression (`restrict`), then on the section recurrence of the progression.
"""
function block_channels(ctx, bd, per, r, approx)
  time() > DEADLINE[] && return nothing
  q = section_recurrence(ctx, bd.p, per, r)
  (q === nothing || iszero(q[1])) && return nothing
  m0 = max(0, cld(bd.kreg - r, per))
  xval = m -> beta_at(ctx, bd, per * m + r)
  gs = qhyper(ctx, q)
  dec = isempty(gs) ? nothing : decompose(ctx, q, gs, xval, m0)
  dec === nothing || return (; exact = true, ratios = gs, coeffs = dec[2], m1 = dec[1], pole = 0)
  a1 = get!(() -> fitted_channels(ctx, bd, 1, 0), approx, 1)
  a1 === nothing || return restrict(ctx, a1, per, r)
  return per == 1 ? nothing : fitted_channels(ctx, bd, per, r)
end

"The remainder fit along n = per·m + r (see `block_channels`), or nothing."
function fitted_channels(ctx, bd, per, r)
  time() > DEADLINE[] && return nothing
  q = section_recurrence(ctx, bd.p, per, r)
  (q === nothing || iszero(q[1])) && return nothing
  k = length(q) - 1
  m0 = max(0, cld(bd.kreg - r, per))
  els = hyper_elements(ctx, q)
  isempty(els) && return nothing
  fit = remainder_fit(ctx, els, q)
  fit === nothing && return nothing
  s, _ = fit
  idx = [i for i in eachindex(s) if !iszero(s[i])]
  isempty(idx) && return nothing
  # w_i is hypergeometric once y_(m−k), …, y_m are defined (concomitant), and m ≥ m0
  M0 = maximum([m0; [first_regular(ctx, els[i].γ, 0) + k for i in idx]])
  ratios = [els[i].ω * zsub(ctx, s[i], 1) // s[i] for i in idx]
  m1 = maximum([M0; [first_regular(ctx, x, M0) for x in [ratios; s[idx]]]])
  xval = m -> beta_at(ctx, bd, per * m + r)
  w(i, m) = sum(toK(ctx, at_tk(ctx, els[i].ℓ[j], m)) * xval(m + j) for j in 1:k)
  for i in idx                                  # a cheap check of the concomitant
    w(i, m1 + 1) == toK(ctx, at_tk(ctx, els[i].ω, m1)) * w(i, m1) || error("concomitant check failed")
  end
  coeffs = [toF(ctx, toK(ctx, at_tk(ctx, s[i], m1)) * w(i, m1)) for i in idx]
  pole = maximum(-zorder(ctx, x) for x in s[idx]; init = 0)
  return (; exact = false, ratios, coeffs, m1, pole)
end

"""
    remainder_test(ctx, rd, per, r, cache) -> result or nothing

The channel test with remainders (section "Hypergeometric elements"). S is additive
over the blocks of the reading rd, and each block's β along n = per·m + r is written
as channels, exactly or up to a remainder that tends to 0 (`block_channels`, cached
per block and progression). If the union of these channels tends to 0
(`merge_channels`, `channel_proof`), so does β along the progression, and S(Δ) = 0.
"""
function remainder_test(ctx, rd, per, r, cache)
  parts = []
  for (k, (name, B)) in enumerate(zip(rd.names, rd.systems))
    bd = get!(() -> try block_reading(ctx, name, B) catch; nothing end, cache, (k, name))
    bd === nothing && return nothing
    approx = get!(() -> Dict{Int, Any}(), cache, (k, name, :approx))
    ch = get!(() -> try block_channels(ctx, bd, per, r, approx) catch; nothing end, cache, (k, name, per, r))
    ch === nothing && return nothing
    push!(parts, ch)
  end
  m1 = maximum(p.m1 for p in parts)
  gs = reduce(vcat, [p.ratios for p in parts])
  a = reduce(vcat, [renormalize(ctx, p.ratios, p.coeffs, p.m1, m1) for p in parts])
  merged = try merge_channels(ctx, gs, a, m1) catch; nothing end
  merged === nothing && return nothing
  gs, a, m1 = merged
  proof = try channel_proof(ctx, gs, a, m1) catch; nothing end
  proof === nothing && return nothing
  return (; period = per, residue = r, m1, ratios = gs, coeffs = a,
            remainders = [p.exact ? :none : p.pole for p in parts], proof...)
end

