"""
    setup()

Create K = Q(t), the quantum plane A, the operator algebra O, and the field
F = Q(t, z) = Frac(Q[t, z]) used for recurrences. Oscar's relation matrix lists,
above the diagonal, the product g_j * g_i (i < j).
"""
function setup()
  K, t = rational_function_field(QQ, :t)
  R, (x, y) = polynomial_ring(K, [:X, :Y])
  A, (X, Y) = pbw_algebra(R, strictly_upper_triangular_matrix([t*x*y]), deglex(gens(R)))  # Y*X = t X*Y
  S, (u, v) = polynomial_ring(K, [:Y, :T])
  O, (Yo, T) = pbw_algebra(S, strictly_upper_triangular_matrix([t*u*v]), deglex(gens(S)))  # T*Y = t Y*T
  R2, (tq, zq) = polynomial_ring(QQ, [:t, :z])
  F = fraction_field(R2)
  return (; K, t, A, X, Y, O, Yo, T, R2, tq, zq, F, tF = F(tq), zF = F(zq))
end

"""
    pbw_terms(h)

Terms of a PBW element h as tuples (c, e1, e2), meaning c * g1^e1 * g2^e2 in
normal order: c Y^e1 T^e2 for h ∈ O, and c X^e1 Y^e2 for h ∈ A. Coefficients lie
in coefficient_ring(parent(h)) = K. (`base_ring` of a PBW algebra is its
underlying commutative polynomial ring, not K.)
"""
function pbw_terms(h)
  cs = AbstractAlgebra.coefficients(h)
  es = AbstractAlgebra.exponent_vectors(h)
  return [(c, e[1], e[2]) for (c, e) in zip(cs, es)]
end

"The operator Σ c Y^b T^a ∈ O, given its terms (c, b, a)."
operator(ctx, terms) = sum((ctx.O(c) * ctx.Yo^b * ctx.T^a for (c, b, a) in terms); init = zero(ctx.O))

"Degree in Y of an operator (-1 for the zero operator)."
ydeg(h) = maximum((b for (_, b, _) in pbw_terms(h)); init = -1)

"t^k ∈ K for any integer k."
tpow(ctx, k) = k >= 0 ? ctx.t^k : inv(ctx.t)^(-k)

"t-adic valuation ν(x) of x ∈ K = Q(t); INF for x = 0."
function valuation_t(x)
  iszero(x) && return INF
  low(p) = minimum(i for i in 0:degree(p) if !iszero(coeff(p, i)))
  return low(numerator(x)) - low(denominator(x))
end

# ---- the field F = Q(t, z) --------------------------------------------------

"x ∈ K as an element of F."
function toF(ctx, x)
  p2(p) = sum((coeff(p, i) * ctx.tq^i for i in 0:degree(p)); init = zero(ctx.R2))
  return p2(numerator(x)) // p2(denominator(x))
end

"x ∈ F free of z, as an element of K."
function toK(ctx, x)
  p1(p) = sum((c * ctx.t^e[1] for (c, e) in zip(AbstractAlgebra.coefficients(p),
                                                AbstractAlgebra.exponent_vectors(p))); init = zero(ctx.K))
  return p1(numerator(x)) // p1(denominator(x))
end

"t-adic valuation of x ∈ F free of z; INF for x = 0."
function tval(x)
  iszero(x) && return INF
  low(p) = minimum(e[1] for e in AbstractAlgebra.exponent_vectors(p))
  return low(numerator(x)) - low(denominator(x))
end

"""
    zsub(ctx, g, a, b = 1)

g(t, t^a z^b) for g ∈ F; the exponent a may be negative. Monomials are remapped
directly, t^i z^j ↦ t^(i + a j) z^(b j), with a power of t moved to the
denominator when needed. zsub(ctx, g, k, 0) is the value g(t^k) ∈ K ⊂ F.
"""
function zsub(ctx, g, a, b = 1)
  function remap(p)
    es = [(e[1] + a * e[2], b * e[2]) for e in AbstractAlgebra.exponent_vectors(p)]
    s = max(0, -minimum(first, es; init = 0))
    build = MPolyBuildCtx(ctx.R2)
    for (c, (i, j)) in zip(AbstractAlgebra.coefficients(p), es)
      push_term!(build, c, [i + s, j])
    end
    return finish(build), s
  end
  (n, sn), (d, sd) = remap(numerator(g)), remap(denominator(g))
  return (n * ctx.tq^sd) // (d * ctx.tq^sn)
end

"g(t^k) ∈ F for g ∈ F (an element free of z)."
at_tk(ctx, g, k) = zsub(ctx, g, k, 0)

"Degree in z of g ∈ F, a polynomial in z over K (its denominator is free of z)."
zdeg(g) = iszero(g) ? -1 : degree(numerator(g), 2)

"Coefficients in K ⊂ F of g ∈ F, a polynomial in z over K: g = Σ_j cs[j+1] z^j."
function zcoeffs(ctx, g)
  @assert degree(denominator(g), 2) <= 0
  n = numerator(g)
  out = [zero(ctx.R2) for _ in 0:zdeg(g)]
  for (c, e) in zip(AbstractAlgebra.coefficients(n), AbstractAlgebra.exponent_vectors(n))
    out[e[2] + 1] += c * ctx.tq^e[1]
  end
  return [x // denominator(g) for x in out]
end

"Polynomial in z over K with coefficients cs (cs[j+1] at z^j)."
from_zcoeffs(ctx, cs) = sum((c * ctx.zF^(j - 1) for (j, c) in enumerate(cs)); init = zero(ctx.F))

# ---- linear algebra over a field (K or F), on plain Julia matrices -------------
# Gauss–Jordan elimination with normalized fractions keeps the entries small; the
# generic fraction-free routines are much slower on these systems.

"Reduced row echelon form of M over the field R: (E, pivot columns)."
function rref_field(R, M::AbstractMatrix)
  E = copy(M)
  m, n = size(E)
  piv = Int[]
  for c in 1:n
    r = length(piv) + 1
    r > m && break
    p = findfirst(i -> !iszero(E[i, c]), r:m)
    p === nothing && continue
    E[[r, r + p - 1], :] = E[[r + p - 1, r], :]
    s = inv(E[r, c])
    E[r, :] = [x * s for x in E[r, :]]
    for i in 1:m
      (i == r || iszero(E[i, c])) && continue
      f = E[i, c]
      E[i, :] = [x - f * y for (x, y) in zip(E[i, :], E[r, :])]
    end
    push!(piv, c)
  end
  return E, piv
end

"A basis of the right kernel {x : M x = 0} of M over the field R."
function kernel_field(R, M::AbstractMatrix)
  E, piv = rref_field(R, M)
  n = size(M, 2)
  out = Vector{elem_type(R)}[]
  for free in setdiff(1:n, piv)
    x = [i == free ? one(R) : zero(R) for i in 1:n]
    for (i, c) in enumerate(piv)
      x[c] = -E[i, free]
    end
    push!(out, x)
  end
  return out
end

"A solution x of M x = b over the field R, or `nothing`."
function solve_field(R, M::AbstractMatrix, b::AbstractVector)
  n = size(M, 2)
  E, piv = rref_field(R, hcat(M, b))
  n + 1 in piv && return nothing               # a row 0 = 1
  x = [zero(R) for _ in 1:n]
  for (i, c) in enumerate(piv)
    x[c] = E[i, n + 1]
  end
  return x
end

"Product of Julia matrices with entries in a ring (no zero element needed)."
matmul(A, B) = [sum(A[i, k] * B[k, j] for k in axes(A, 2)) for i in axes(A, 1), j in axes(B, 2)]

# Systems whose entries are free of z are solved over K = Q(t): univariate gcds are
# much cheaper than those of Q[t, z].
"Entries of F free of z, as elements of K."
over_K(ctx, M) = map(x -> toK(ctx, x), M)

